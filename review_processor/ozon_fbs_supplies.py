def get_ship_all_collect_state() -> dict[str, Any]:
    with _collect_lock:
        st = dict(_collect_state)
        st["errors"] = [dict(x) if isinstance(x, dict) else x for x in (_collect_state.get("errors") or [])]
        st["created_supplies"] = [
            dict(x) if isinstance(x, dict) else x
            for x in (_collect_state.get("created_supplies") or [])
        ]
        st["group_lines"] = list(_collect_state.get("group_lines") or [])
        st["shipped_numbers"] = list(_collect_state.get("shipped_numbers") or [])
        return st


def request_ship_all_collect_stop() -> bool:
    with _collect_lock:
        if _collect_state.get("in_progress"):
            _collect_state["cancel_requested"] = True
            return True
    return False


def _set_collect_progress(**kwargs: Any) -> None:
    with _collect_lock:
        _collect_state.update(kwargs)


def execute_ship_all_collect(
    repo: ReviewRepository,
    *,
    user_id: int,
    source_id: int,
    client_id: str,
    api_key: str,
    decisions: list[dict[str, Any]],
    progress: Any | None = None,
    stop_requested: Any | None = None,
    ship_pause_sec: float = OZON_FBS_SHIP_ALL_PAUSE_SEC,
) -> dict[str, Any]:
    """Ship on Ozon + create/add local supplies from decisions.

    Ozon has no batch ship — one ``/v4/posting/fbs/ship`` per posting.
    Progress callback: ``progress(done, total, message)``.
    """
    ensure_ozon_fbs_supply_schema(repo)
    preview = preview_ship_all_collect(repo, user_id=user_id, source_id=source_id)
    groups_by_key = {str(g.get("group_key")): g for g in preview.get("groups") or []}
    if not groups_by_key:
        out = {
            "ok": True,
            "total": 0,
            "shipped": 0,
            "failed": 0,
            "done": 0,
            "created_supplies": [],
            "errors": [],
            "message": "Нет отправлений в «Ожидают сборки»",
            "goto_awaiting_deliver": False,
            "shipped_numbers": [],
            "group_lines": [],
        }
        if progress:
            progress(0, 0, out["message"])
        return out

    client = oz.OzonFbsClient(client_id, api_key)
    shipped: list[str] = []
    shipped_result: list[str] = []
    errors: list[dict[str, str]] = []
    created: list[dict[str, str]] = []
    group_lines: list[str] = []

    open_names = {
        str(s.get("name") or "").strip()
        for s in list_open_supplies(repo, user_id=user_id, source_id=source_id)
        if str(s.get("name") or "").strip()
    }
    source_name = _source_display_name(repo, user_id=user_id, source_id=source_id)

    # Flatten for progress total.
    work_groups: list[tuple[dict[str, Any], dict[str, Any], list[str]]] = []
    for dec in decisions or []:
        if not isinstance(dec, dict):
            continue
        gkey = str(dec.get("group_key") or "").strip()
        group = groups_by_key.get(gkey)
        if not group:
            errors.append({"posting_number": gkey or "?", "error": "Группа не найдена"})
            continue
        posting_numbers = [str(x).strip() for x in (group.get("posting_numbers") or []) if str(x).strip()]
        if posting_numbers:
            work_groups.append((dec, group, posting_numbers))
    total = sum(len(pns) for _, _, pns in work_groups)
    done = 0
    if progress:
        progress(0, total, f"Сборка… 0 из {total}")

    def _stopped() -> bool:
        return bool(stop_requested and stop_requested())

    for dec, group, posting_numbers in work_groups:
        if _stopped():
            break
        gkey = str(dec.get("group_key") or group.get("group_key") or "").strip()
        action = str(dec.get("action") or group.get("mode") or "create").strip().lower()
        if action == "add_one":
            action = "add"
        shipped_here: list[str] = []
        for pn in posting_numbers:
            if _stopped():
                break
            try:
                ship_out = oz_detail.ship_posting(
                    repo,
                    user_id=user_id,
                    source_id=source_id,
                    posting_number=pn,
                    client_id=client_id,
                    api_key=api_key,
                    client=client,
                    fast=True,
                )
                result_pns = [
                    str(x).strip()
                    for x in (ship_out.get("posting_numbers") or [pn])
                    if str(x).strip()
                ]
                if not result_pns:
                    result_pns = [pn]
                shipped.append(pn)
                for rpn in result_pns:
                    if rpn not in shipped_here:
                        shipped_here.append(rpn)
                    if rpn not in shipped_result:
                        shipped_result.append(rpn)
            except Exception as exc:
                errors.append({"posting_number": pn, "error": str(exc)})
                _log.warning("ozon ship-all %s failed: %s", pn, exc)
            done += 1
            if progress:
                progress(
                    done,
                    total,
                    f"Сборка… {done} из {total}"
                    + (f" · ошибок {len(errors)}" if errors else ""),
                )
            if ship_pause_sec and ship_pause_sec > 0:
                time.sleep(float(ship_pause_sec))

        if not shipped_here:
            continue

        wh_id = group.get("warehouse_id")
        wh_name = str(group.get("warehouse_name") or "")
        try:
            if action == "create":
                name = str(dec.get("name") or group.get("suggested_name") or "").strip()
                name = _unique_supply_name(
                    name or default_supply_name(source_name=source_name),
                    open_names,
                )
                sid = _create_local_supply(
                    repo,
                    user_id=user_id,
                    source_id=source_id,
                    name=name,
                    warehouse_id=wh_id,
                    warehouse_name=wh_name,
                    posting_numbers=shipped_here,
                )
                open_names.add(name)
                created.append({"supply_id": sid, "name": name})
                group_lines.append(f"{name}: {len(shipped_here)} отпр.")
            else:
                sid = str(
                    dec.get("supply_id") or group.get("default_supply_id") or ""
                ).strip()
                if not sid:
                    raise RuntimeError("Не выбрана поставка")
                if not _is_collect_target_supply(
                    repo, user_id=user_id, source_id=source_id, supply_id=sid
                ):
                    raise RuntimeError(
                        "Поставка «Доставляются» недоступна для ручного сбора"
                    )
                _add_postings_to_supply(
                    repo,
                    user_id=user_id,
                    source_id=source_id,
                    supply_id=sid,
                    posting_numbers=shipped_here,
                )
                sname = next(
                    (
                        str(c.get("name") or sid)
                        for c in (group.get("compatible_supplies") or [])
                        if str(c.get("supply_id")) == sid
                    ),
                    sid,
                )
                group_lines.append(f"{sname}: +{len(shipped_here)} отпр.")
        except Exception as exc:
            errors.append({"posting_number": gkey, "error": str(exc)})

    shipped_n = len(shipped)
    failed_n = len(errors)
    force_numbers = list(shipped_result) if shipped_result else list(shipped)
    stopped = _stopped()
    ok = shipped_n > 0 and failed_n == 0 and not stopped
    split_extra = max(len(shipped_result) - shipped_n, 0) if shipped_result else 0
    if stopped and shipped_n:
        message = f"Остановлено. Собрано {shipped_n} из {total}"
    elif stopped:
        message = "Остановлено"
    elif shipped_n and not failed_n:
        if split_extra:
            message = (
                f"Собрано {shipped_n} → {len(shipped_result)} отправлений "
                f"(+{split_extra} после разбиения) → «Ожидают отгрузки»"
            )
        else:
            message = f"Собрано {shipped_n} отправлений → «Ожидают отгрузки»"
    elif shipped_n:
        message = f"Собрано {shipped_n}, ошибок {failed_n}"
    else:
        message = f"Не удалось собрать отправления ({failed_n})"
    if progress:
        progress(done, total, message)
    if force_numbers:
        placeholders = ", ".join("?" for _ in force_numbers)
        with repo._connect() as conn:
            conn.execute(
                repo._sql(
                    f"""
                    UPDATE ozon_fbs_postings
                    SET status = ?, tab = ?
                    WHERE user_id = ? AND source_id = ?
                      AND posting_number IN ({placeholders})
                      AND LOWER(COALESCE(tab, '')) IN (?, ?)
                    """
                ),
                (
                    oz.TAB_AWAITING_DELIVER,
                    oz.TAB_AWAITING_DELIVER,
                    user_id,
                    source_id,
                    *force_numbers,
                    oz.TAB_AWAITING_PACKAGING,
                    oz.TAB_AWAITING_DELIVER,
                ),
            )
    return {
        "ok": ok,
        "total": total or int(preview.get("posting_count") or 0),
        "done": done,
        "shipped": shipped_n,
        "failed": failed_n,
        "shipped_numbers": shipped_result or shipped,
        "result_posting_count": len(shipped_result) if shipped_result else shipped_n,
        "extra_postings": split_extra,
        "created_supplies": created,
        "group_lines": group_lines,
        "errors": errors,
        "message": message,
        "goto_awaiting_deliver": shipped_n > 0,
        "stopped": stopped,
    }


def start_ship_all_collect_thread(
    *,
    repo: ReviewRepository,
    user_id: int,
    source_id: int,
    client_id: str,
    api_key: str,
    decisions: list[dict[str, Any]],
) -> tuple[bool, str]:
    """Background «Собрать все» — same UX pattern as Ozon FBS sync."""
    with _collect_lock:
        if _collect_state.get("in_progress"):
            return False, "Сборка уже выполняется"
        _collect_state.update(
            {
                "in_progress": True,
                "cancel_requested": False,
                "source_id": int(source_id),
                "total": 0,
                "done": 0,
                "shipped": 0,
                "failed": 0,
                "message": "Запуск сборки…",
                "errors": [],
                "created_supplies": [],
                "group_lines": [],
                "shipped_numbers": [],
                "goto_awaiting_deliver": False,
                "ok": True,
            }
        )

    def _run() -> None:
        def _progress(done: int, total: int, message: str) -> None:
            with _collect_lock:
                _collect_state["done"] = int(done)
                _collect_state["total"] = int(total)
                _collect_state["message"] = str(message or "")

        def _stop() -> bool:
            with _collect_lock:
                return bool(_collect_state.get("cancel_requested"))

        try:
            result = execute_ship_all_collect(
                repo,
                user_id=user_id,
                source_id=source_id,
                client_id=client_id,
                api_key=api_key,
                decisions=decisions,
                progress=_progress,
                stop_requested=_stop,
            )
            with _collect_lock:
                _collect_state.update(
                    {
                        "in_progress": False,
                        "total": int(result.get("total") or 0),
                        "done": int(result.get("done") or result.get("total") or 0),
                        "shipped": int(result.get("shipped") or 0),
                        "failed": int(result.get("failed") or 0),
                        "message": str(result.get("message") or ""),
                        "errors": list(result.get("errors") or []),
                        "created_supplies": list(result.get("created_supplies") or []),
                        "group_lines": list(result.get("group_lines") or []),
                        "shipped_numbers": list(result.get("shipped_numbers") or []),
                        "goto_awaiting_deliver": bool(result.get("goto_awaiting_deliver")),
                        "ok": bool(result.get("ok")),
                    }
                )
        except Exception as exc:
            _log.exception("ozon ship-all collect failed")
            with _collect_lock:
                _collect_state.update(
                    {
                        "in_progress": False,
                        "ok": False,
                        "message": f"Ошибка сборки: {exc}",
                        "errors": [{"posting_number": "?", "error": str(exc)}],
                    }
                )

    threading.Thread(target=_run, name="ozon-fbs-ship-all", daemon=True).start()
    return True, "Сборка запущена"


