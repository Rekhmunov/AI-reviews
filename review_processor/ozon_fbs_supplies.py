def ensure_ozon_fbs_supply_schema(repo: ReviewRepository) -> None:
    oz.ensure_ozon_fbs_tables(repo)
    with repo._connect() as conn:
        try:
            conn.execute(
                "ALTER TABLE ozon_fbs_postings "
                "ADD COLUMN IF NOT EXISTS supply_id TEXT NOT NULL DEFAULT ''"
            )
        except Exception:
            try:
                conn.execute(
                    "ALTER TABLE ozon_fbs_postings "
                    "ADD COLUMN supply_id TEXT NOT NULL DEFAULT ''"
                )
            except Exception:
                pass
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS ozon_fbs_supplies (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL,
                source_id BIGINT NOT NULL,
                supply_id TEXT NOT NULL,
                name TEXT NOT NULL DEFAULT '',
                warehouse_id BIGINT,
                warehouse_name TEXT NOT NULL DEFAULT '',
                done BOOLEAN NOT NULL DEFAULT FALSE,
                posting_numbers_json TEXT NOT NULL DEFAULT '[]',
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                UNIQUE (user_id, source_id, supply_id)
            )
            """
        )
        conn.execute(
            repo._sql(
                "CREATE INDEX IF NOT EXISTS idx_ozon_fbs_supplies_user_src "
                "ON ozon_fbs_supplies(user_id, source_id, created_at DESC)"
            )
        )
        conn.execute(
            repo._sql(
                "CREATE INDEX IF NOT EXISTS idx_ozon_fbs_postings_supply "
                "ON ozon_fbs_postings(user_id, source_id, supply_id)"
            )
        )


def _source_display_name(
    repo: ReviewRepository, *, user_id: int, source_id: int
) -> str:
    src = repo.get_supply_source_with_key(user_id=user_id, source_id=source_id)
    name = str((src or {}).get("name") or "").strip()
    return name or f"Источник {source_id}"


def default_supply_name(*, source_name: str, when: datetime | None = None) -> str:
    """``Поставка Название источника от ДД.ММ.ГГГГ`` (MSK)."""
    dt = when or datetime.now(ZoneInfo("Europe/Moscow"))
    label = str(source_name or "").strip() or "—"
    return f"Поставка {label} от {dt.strftime('%d.%m.%Y')}"


def _unique_supply_name(base: str, existing_names: set[str]) -> str:
    name = str(base or "").strip() or "Поставка"
    if name not in existing_names:
        return name
    for i in range(2, 100):
        candidate = f"{name} ({i})"
        if candidate not in existing_names:
            return candidate
    return f"{name} · {int(time.time())}"


def _new_supply_id(source_id: int) -> str:
    stamp = datetime.now(ZoneInfo("Europe/Moscow")).strftime("%Y%m%d")
    return f"{SUPPLY_ID_PREFIX}-{int(source_id)}-{stamp}-{secrets.token_hex(3).upper()}"


def _parse_json_list(raw: object) -> list[Any]:
    try:
        data = json.loads(raw or "[]")
    except Exception:
        return []
    return data if isinstance(data, list) else []


def _esc(value: object) -> str:
    return (
        str(value or "")
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


def list_open_supplies(
    repo: ReviewRepository, *, user_id: int, source_id: int
) -> list[dict[str, Any]]:
    ensure_ozon_fbs_supply_schema(repo)
    with repo._connect() as conn:
        rows = conn.execute(
            repo._sql(
                """
                SELECT * FROM ozon_fbs_supplies
                WHERE user_id = ? AND source_id = ? AND COALESCE(done, FALSE) = FALSE
                ORDER BY created_at DESC
                """
            ),
            (user_id, source_id),
        ).fetchall()
    out: list[dict[str, Any]] = []
    for row in rows:
        d = repo._row_to_dict(row)
        nums = [
            str(x).strip()
            for x in _parse_json_list(d.get("posting_numbers_json"))
            if str(x).strip()
        ]
        d["posting_numbers"] = nums
        d["order_count"] = len(nums)
        d["is_empty"] = len(nums) == 0
        out.append(d)
    return out


def _supply_ids_with_tab(
    repo: ReviewRepository, *, user_id: int, source_id: int, tab: str
) -> set[str]:
    """Distinct local supply ids that have postings on the given Ozon tab."""
    ensure_ozon_fbs_supply_schema(repo)
    tab_key = str(tab or "").strip()
    if not tab_key:
        return set()
    with repo._connect() as conn:
        rows = conn.execute(
            repo._sql(
                """
                SELECT DISTINCT supply_id FROM ozon_fbs_postings
                WHERE user_id = ? AND source_id = ? AND tab = ?
                  AND COALESCE(supply_id, '') != ''
                """
            ),
            (user_id, source_id, tab_key),
        ).fetchall()
    out: set[str] = set()
    for row in rows:
        sid = str(row["supply_id"] if hasattr(row, "keys") else row[0]).strip()
        if sid:
            out.add(sid)
    return out


def list_collect_target_supplies(
    repo: ReviewRepository, *, user_id: int, source_id: int
) -> list[dict[str, Any]]:
    """Open supplies eligible for collect/selection → «Ожидают отгрузки».

    «Доставляются» supplies are excluded (Ozon sync or local «Перенести в доставку»).
    Empty supplies tied to delivering-only postings are excluded as well.
    """
    open_supplies = list_open_supplies(repo, user_id=user_id, source_id=source_id)
    awaiting_ids = _supply_ids_with_tab(
        repo, user_id=user_id, source_id=source_id, tab=oz.TAB_AWAITING_DELIVER
    )
    delivering_ids = _supply_ids_with_tab(
        repo, user_id=user_id, source_id=source_id, tab=oz.TAB_DELIVERING
    )
    eligible: list[dict[str, Any]] = []
    for s in open_supplies:
        sid = str(s.get("supply_id") or "").strip()
        if not sid:
            continue
        if sid in awaiting_ids:
            eligible.append(s)
        elif s.get("is_empty") and sid not in delivering_ids:
            eligible.append(s)
    return eligible


def _is_collect_target_supply(
    repo: ReviewRepository, *, user_id: int, source_id: int, supply_id: str
) -> bool:
    sid = str(supply_id or "").strip()
    if not sid:
        return False
    return sid in {
        str(s.get("supply_id") or "").strip()
        for s in list_collect_target_supplies(
            repo, user_id=user_id, source_id=source_id
        )
        if str(s.get("supply_id") or "").strip()
    }


def _load_awaiting_packaging_rows(
    repo: ReviewRepository, *, user_id: int, source_id: int
) -> list[dict[str, Any]]:
    ensure_ozon_fbs_supply_schema(repo)
    with repo._connect() as conn:
        rows = conn.execute(
            repo._sql(
                """
                SELECT * FROM ozon_fbs_postings
                WHERE user_id = ? AND source_id = ? AND tab = ?
                  AND COALESCE(supply_id, '') = ''
                ORDER BY created_at_ozon DESC NULLS LAST, posting_number DESC
                """
            ),
            (user_id, source_id, oz.TAB_AWAITING_PACKAGING),
        ).fetchall()
    return [repo._row_to_dict(r) for r in rows]


def preview_ship_all_collect(
    repo: ReviewRepository, *, user_id: int, source_id: int
) -> dict[str, Any]:
    """Plan local supplies for «Собрать все заказы» (group by warehouse)."""
    ensure_ozon_fbs_supply_schema(repo)
    rows = _load_awaiting_packaging_rows(repo, user_id=user_id, source_id=source_id)
    buckets: dict[Any, list[dict[str, Any]]] = {}
    for row in rows:
        wh = row.get("warehouse_id")
        buckets.setdefault(wh, []).append(row)

    all_open = list_open_supplies(repo, user_id=user_id, source_id=source_id)
    open_supplies = list_collect_target_supplies(
        repo, user_id=user_id, source_id=source_id
    )
    existing_names = {
        str(s.get("name") or "").strip()
        for s in all_open
        if str(s.get("name") or "").strip()
    }
    reserved = set(existing_names)
    empties_pool = [s for s in open_supplies if s.get("is_empty")]

    source_name = _source_display_name(repo, user_id=user_id, source_id=source_id)
    groups: list[dict[str, Any]] = []
    for warehouse_id in sorted(buckets.keys(), key=lambda x: (x is None, str(x))):
        bucket = buckets[warehouse_id]
        posting_numbers = [
            str(r.get("posting_number") or "").strip()
            for r in bucket
            if str(r.get("posting_number") or "").strip()
        ]
        wh_name = str(bucket[0].get("warehouse_name") or "").strip() if bucket else ""
        matching = []
        for s in open_supplies:
            if s.get("is_empty"):
                continue
            sw = s.get("warehouse_id")
            if warehouse_id is None and sw is None:
                matching.append(s)
            elif (
                warehouse_id is not None
                and sw is not None
                and int(sw) == int(warehouse_id)
            ):
                matching.append(s)
        base = default_supply_name(source_name=source_name)
        suggested = _unique_supply_name(base, reserved)
        reserved.add(suggested)
        group_key = f"wh{warehouse_id if warehouse_id is not None else 'none'}"
        label = wh_name or (
            f"склад {warehouse_id}" if warehouse_id is not None else "склад —"
        )
        if len(matching) >= 2:
            mode = "choose"
            candidates = list(matching)
            default_supply_id = str(matching[0].get("supply_id") or "")
        elif len(matching) == 1:
            mode = "add_one"
            candidates = list(matching)
            default_supply_id = str(matching[0].get("supply_id") or "")
        elif empties_pool:
            chosen_empty = empties_pool[0]
            mode = "add_one"
            candidates = [chosen_empty]
            default_supply_id = str(chosen_empty.get("supply_id") or "")
            empties_pool = empties_pool[1:]
        else:
            mode = "create"
            candidates = []
            default_supply_id = ""
        compatible = [
            {
                "supply_id": s.get("supply_id"),
                "name": s.get("name") or s.get("supply_id"),
                "is_empty": bool(s.get("is_empty")),
                "orders_count": int(s.get("order_count") or 0),
                "warehouse_name": s.get("warehouse_name") or "",
            }
            for s in candidates
        ]
        split = oz_detail.ship_split_preview(bucket)
        groups.append(
            {
                "group_key": group_key,
                "warehouse_id": warehouse_id,
                "warehouse_name": wh_name,
                "label": label,
                "posting_numbers": posting_numbers,
                "order_count": len(posting_numbers),
                "multi_posting_count": split["multi_posting_count"],
                "result_posting_count": split["result_posting_count"],
                "extra_postings": split["extra_postings"],
                "suggested_name": suggested,
                "name_conflict": False,
                "compatible_supplies": compatible,
                "mode": mode,
                "default_supply_id": default_supply_id,
            }
        )

    needs_modal = any(g.get("mode") in ("create", "choose") for g in groups)
    split_all = oz_detail.ship_split_preview(rows)
    return {
        "ok": True,
        "mgt_count": len(rows),
        "posting_count": len(rows),
        "multi_posting_count": split_all["multi_posting_count"],
        "result_posting_count": split_all["result_posting_count"],
        "extra_postings": split_all["extra_postings"],
        "groups": groups,
        "needs_modal": needs_modal,
        "existing_names": sorted(existing_names),
        "source_name": source_name,
    }


def _create_local_supply(
    repo: ReviewRepository,
    *,
    user_id: int,
    source_id: int,
    name: str,
    warehouse_id: object,
    warehouse_name: str,
    posting_numbers: list[str],
    force_tab: str | None = oz.TAB_AWAITING_DELIVER,
) -> str:
    ensure_ozon_fbs_supply_schema(repo)
    sid = _new_supply_id(source_id)
    nums = [str(x).strip() for x in posting_numbers if str(x).strip()]
    try:
        wh_id = int(warehouse_id) if warehouse_id is not None else None
    except (TypeError, ValueError):
        wh_id = None
    with repo._connect() as conn:
        conn.execute(
            repo._sql(
                """
                INSERT INTO ozon_fbs_supplies (
                    user_id, source_id, supply_id, name, warehouse_id, warehouse_name,
                    done, posting_numbers_json, created_at, updated_at
                ) VALUES (?, ?, ?, ?, ?, ?, FALSE, ?, NOW(), NOW())
                """
            ),
            (
                user_id,
                source_id,
                sid,
                str(name or "").strip()
                or default_supply_name(
                    source_name=_source_display_name(
                        repo, user_id=user_id, source_id=source_id
                    )
                ),
                wh_id,
                str(warehouse_name or "").strip(),
                json.dumps(nums, ensure_ascii=False),
            ),
        )
        if nums:
            placeholders = ", ".join("?" for _ in nums)
            if force_tab:
                conn.execute(
                    repo._sql(
                        f"""
                        UPDATE ozon_fbs_postings
                        SET supply_id = ?, tab = ?, status = ?
                        WHERE user_id = ? AND source_id = ?
                          AND posting_number IN ({placeholders})
                        """
                    ),
                    (
                        sid,
                        str(force_tab),
                        str(force_tab),
                        user_id,
                        source_id,
                        *nums,
                    ),
                )
            else:
                conn.execute(
                    repo._sql(
                        f"""
                        UPDATE ozon_fbs_postings
                        SET supply_id = ?
                        WHERE user_id = ? AND source_id = ?
                          AND posting_number IN ({placeholders})
                        """
                    ),
                    (sid, user_id, source_id, *nums),
                )
    return sid


def _add_postings_to_supply(
    repo: ReviewRepository,
    *,
    user_id: int,
    source_id: int,
    supply_id: str,
    posting_numbers: list[str],
) -> None:
    ensure_ozon_fbs_supply_schema(repo)
    sid = str(supply_id or "").strip()
    nums = [str(x).strip() for x in posting_numbers if str(x).strip()]
    if not sid or not nums:
        return
    with repo._connect() as conn:
        row = conn.execute(
            repo._sql(
                """
                SELECT posting_numbers_json FROM ozon_fbs_supplies
                WHERE user_id = ? AND source_id = ? AND supply_id = ?
                """
            ),
            (user_id, source_id, sid),
        ).fetchone()
        if not row:
            raise RuntimeError(f"Поставка {sid} не найдена")
        raw = row["posting_numbers_json"] if hasattr(row, "keys") else row[0]
        existing = [
            str(x).strip()
            for x in _parse_json_list(raw)
            if str(x).strip()
        ]
        merged = existing[:]
        for n in nums:
            if n not in merged:
                merged.append(n)
        conn.execute(
            repo._sql(
                """
                UPDATE ozon_fbs_supplies
                SET posting_numbers_json = ?, updated_at = NOW()
                WHERE user_id = ? AND source_id = ? AND supply_id = ?
                """
            ),
            (json.dumps(merged, ensure_ascii=False), user_id, source_id, sid),
        )
        placeholders = ", ".join("?" for _ in nums)
        conn.execute(
            repo._sql(
                f"""
                UPDATE ozon_fbs_postings
                SET supply_id = ?, tab = ?, status = ?
                WHERE user_id = ? AND source_id = ?
                  AND posting_number IN ({placeholders})
                """
            ),
            (
                sid,
                oz.TAB_AWAITING_DELIVER,
                oz.TAB_AWAITING_DELIVER,
                user_id,
                source_id,
                *nums,
            ),
        )


