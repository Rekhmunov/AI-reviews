def delivery_method_for_supply(
    repo: ReviewRepository,
    *,
    user_id: int,
    source_id: int,
    supply_id: str,
) -> dict[str, Any] | None:
    """Resolve Ozon delivery method {id, name} from the first posting in supply."""
    ensure_ozon_fbs_supply_schema(repo)
    sid = str(supply_id or "").strip()
    if not sid:
        return None
    nums = _assembly_posting_numbers_for_supply(
        repo, user_id=user_id, source_id=source_id, supply_id=sid
    )
    if not nums:
        return None
    with repo._connect() as conn:
        row = conn.execute(
            repo._sql(
                """
                SELECT raw_json FROM ozon_fbs_postings
                WHERE user_id = ? AND source_id = ? AND posting_number = ?
                """
            ),
            (user_id, source_id, nums[0]),
        ).fetchone()
    if not row:
        return None
    raw = row["raw_json"] if hasattr(row, "keys") else row[0]
    try:
        posting = json.loads(str(raw or "{}"))
    except json.JSONDecodeError:
        return None
    if not isinstance(posting, dict):
        return None
    dm = posting.get("delivery_method")
    if isinstance(dm, dict):
        try:
            mid = int(dm.get("id") or dm.get("delivery_method_id") or 0)
        except (TypeError, ValueError):
            mid = 0
        name = str(
            dm.get("name")
            or dm.get("delivery_method_name")
            or posting.get("tpl_provider_name")
            or ""
        ).strip()
        if mid > 0:
            return {"id": mid, "name": name or f"Метод {mid}"}
    return None


def delivery_method_id_for_supply(
    repo: ReviewRepository,
    *,
    user_id: int,
    source_id: int,
    supply_id: str,
) -> int | None:
    """Resolve Ozon delivery_method.id from the first posting linked to the supply."""
    info = delivery_method_for_supply(
        repo, user_id=user_id, source_id=source_id, supply_id=supply_id
    )
    if not info:
        return None
    try:
        mid = int(info.get("id") or 0)
        return mid if mid > 0 else None
    except (TypeError, ValueError):
        return None


def refresh_supply_postings_from_ozon(
    repo: ReviewRepository,
    *,
    user_id: int,
    source_id: int,
    posting_numbers: list[str],
    client_id: str,
    api_key: str,
) -> None:
    """Full live Ozon refresh (get_posting) — use sparingly (?refresh=1 on detail)."""
    nums = [str(x).strip() for x in posting_numbers if str(x).strip()]
    if not nums or not str(client_id or "").strip() or not str(api_key or "").strip():
        return
    client = oz.OzonFbsClient(str(client_id).strip(), str(api_key).strip())
    requires_kiz_map = repo.get_product_requires_kiz_map(user_id=user_id)
    for i, pn in enumerate(nums):
        try:
            remote = client.get_posting(pn)
            if isinstance(remote, dict):
                # Catalog «Требует КИЗ» is the Marking gate — do not trust is-required.
                remote = oz.apply_catalog_marking_flags(remote, requires_kiz_map)
                oz.upsert_posting(
                    repo,
                    user_id=user_id,
                    source_id=source_id,
                    posting=remote,
                )
        except Exception as exc:
            _log.warning("ozon supply detail refresh %s: %s", pn, exc)
        if i + 1 < len(nums):
            time.sleep(0.05)




def _clamp_live_check_chunk(value: int | None, *, default: int = OZON_FBS_LIVE_CHECK_CHUNK) -> int:
    try:
        n = int(value) if value is not None else int(default)
    except (TypeError, ValueError):
        n = int(default)
    if n < 1:
        n = int(default)
    return min(n, OZON_FBS_LIVE_CHECK_CHUNK_MAX)


def _empty_marking_resolve() -> dict[str, int]:
    return {
        "updated": 0,
        "checked": 0,
        "remaining": 0,
        "total_pending": 0,
    }


def refresh_supply_marking_flags_from_ozon(
    repo: ReviewRepository,
    *,
    user_id: int,
    source_id: int,
    posting_numbers: list[str],
    client_id: str,
    api_key: str,
    max_postings: int | None = OZON_FBS_LIVE_CHECK_CHUNK,
) -> dict[str, int]:
    """Apply catalog «Требует КИЗ» to postings of the current supply (chunked).

    Only the caller-provided posting list is touched (one supply). Local catalog
    apply is cheap, but upserts are chunked so large supplies do not hang one
    HTTP request. Already-matching postings are skipped so each round advances
    and FE counters stay coherent (проверено + осталось = размер поставки).
    """
    del client_id, api_key
    nums = [str(x).strip() for x in posting_numbers if str(x).strip()]
    if not nums:
        return _empty_marking_resolve()
    seen: set[str] = set()
    unique_nums: list[str] = []
    for pn in nums:
        if pn in seen:
            continue
        seen.add(pn)
        unique_nums.append(pn)
    requires_kiz_map = repo.get_product_requires_kiz_map(user_id=user_id)
    placeholders = ", ".join("?" for _ in unique_nums)
    with repo._connect() as conn:
        rows = conn.execute(
            repo._sql(
                f"""
                SELECT * FROM ozon_fbs_postings
                WHERE user_id = ? AND source_id = ?
                  AND posting_number IN ({placeholders})
                """
            ),
            (user_id, source_id, *unique_nums),
        ).fetchall()
    by_pn = {
        str(repo._row_to_dict(row).get("posting_number") or "").strip(): repo._row_to_dict(row)
        for row in rows
    }

    def _mark_ids(req: object) -> list[str]:
        if not isinstance(req, dict):
            return []
        marks = req.get("products_requiring_mandatory_mark") or []
        if not isinstance(marks, list):
            return []
        return sorted({str(x).strip() for x in marks if str(x).strip()})

    pending: list[tuple[str, dict[str, Any]]] = []
    for pn in unique_nums:
        row = by_pn.get(pn)
        if not row:
            continue
        posting = oz._posting_payload_from_row(row)
        if not posting:
            continue
        enriched = oz.apply_catalog_marking_flags(posting, requires_kiz_map)
        cur_req = posting.get("requirements") if isinstance(posting.get("requirements"), dict) else {}
        new_req = enriched.get("requirements") if isinstance(enriched.get("requirements"), dict) else {}
        already = (
            bool(cur_req.get("marking_is_required_checked"))
            and cur_req.get("marking_check_version") is None
            and _mark_ids(cur_req) == _mark_ids(new_req)
        )
        if already:
            continue
        pending.append((pn, enriched))

    total_pending = len(pending)
    chunk_limit = _clamp_live_check_chunk(max_postings)
    chunk = pending[:chunk_limit]
    remaining = max(0, total_pending - len(chunk))
    if not chunk:
        return {
            "updated": 0,
            "checked": 0,
            "remaining": 0,
            "total_pending": total_pending,
        }

    updated = 0
    for pn, enriched in chunk:
        try:
            oz.upsert_posting(
                repo,
                user_id=user_id,
                source_id=source_id,
                posting=enriched,
            )
            updated += 1
        except Exception as exc:
            _log.warning("ozon supply marking catalog persist %s: %s", pn, exc)
    return {
        "updated": updated,
        "checked": len(chunk),
        "remaining": remaining,
        "total_pending": total_pending,
    }


def resolve_supply_kiz_flags_from_ozon(
    repo: ReviewRepository,
    *,
    user_id: int,
    source_id: int,
    supply_id: str,
    client_id: str,
    api_key: str,
    posting_tab: str | None = None,
    max_postings: int | None = OZON_FBS_LIVE_CHECK_CHUNK,
) -> dict[str, int]:
    """Resolve КИЗ flags for supply postings from Settings → Products catalog."""
    sid = str(supply_id or "").strip()
    if not sid:
        return _empty_marking_resolve()
    tab_key = str(posting_tab or "").strip() or None
    if tab_key:
        nums = _assembly_posting_numbers_for_supply_tab(
            repo,
            user_id=user_id,
            source_id=source_id,
            supply_id=sid,
            tab=tab_key,
        )
    else:
        nums = _assembly_posting_numbers_for_supply(
            repo, user_id=user_id, source_id=source_id, supply_id=sid
        )
    if not nums:
        return _empty_marking_resolve()
    detail = get_supply_detail(
        repo,
        user_id=user_id,
        source_id=source_id,
        supply_id=sid,
        posting_tab=tab_key,
    )
    active: list[str] = []
    for o in detail.get("orders") or []:
        if not isinstance(o, dict) or oz.posting_row_is_cancelled(o):
            continue
        pn = str(o.get("posting_number") or "").strip()
        if pn:
            active.append(pn)
    if not active:
        active = list(nums)
    return refresh_supply_marking_flags_from_ozon(
        repo,
        user_id=user_id,
        source_id=source_id,
        posting_numbers=active,
        client_id=client_id,
        api_key=api_key,
        max_postings=max_postings,
    )


