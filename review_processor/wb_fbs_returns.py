def fetch_goods_return_report(
    *,
    api_key: str,
    date_from: str,
    date_to: str,
    timeout: int = 60,
) -> list[dict[str, Any]]:
    """WB Analytics: GET /api/v1/analytics/goods-return (max 31 days)."""
    params = urlencode(
        {"dateFrom": _parse_iso_date(date_from), "dateTo": _parse_iso_date(date_to)}
    )
    url = f"{WB_ANALYTICS_API}/api/v1/analytics/goods-return?{params}"
    req = urllib.request.Request(
        url,
        method="GET",
        headers={
            "Authorization": str(api_key or "").strip(),
            "Accept": "application/json",
            "User-Agent": "FeedPilot-WBFBS-Returns/1.0",
        },
    )
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            payload = resp.read()
    except urllib.error.HTTPError as exc:
        err = ""
        try:
            err = exc.read().decode("utf-8", errors="replace")[:500]
        except Exception:
            pass
        retry_after = _http_header_get(
            getattr(exc, "headers", None),
            "X-RateLimit-Retry",
            "x-ratelimit-retry",
            "Retry-After",
            "retry-after",
        )
        raise format_wb_goods_return_http_error(
            code=int(exc.code),
            body=err,
            retry_after=retry_after,
            reason=str(exc.reason or ""),
        ) from exc
    if not payload:
        return []
    parsed = json.loads(payload.decode("utf-8"))
    if isinstance(parsed, dict):
        report = parsed.get("report")
        if isinstance(report, list):
            return [x for x in report if isinstance(x, dict)]
    if isinstance(parsed, list):
        return [x for x in parsed if isinstance(x, dict)]
    return []


def fetch_goods_return_report_rated(
    *,
    api_key: str,
    date_from: str,
    date_to: str,
    source_id: int | None = None,
    timeout: int = 60,
) -> list[dict[str, Any]]:
    """Fetch goods-return with per-token cooldown; fail fast on HTTP 429."""
    token_key = _analytics_token_key(api_key)
    ensure_goods_return_not_rate_limited(api_key=api_key)
    with _goods_return_token_rate_slot(api_key=api_key, source_id=source_id):
        try:
            rows = fetch_goods_return_report(
                api_key=api_key,
                date_from=date_from,
                date_to=date_to,
                timeout=timeout,
            )
            _clear_goods_return_token_block(api_key=api_key)
            return rows
        except GoodsReturnHttpError as exc:
            if exc.code == 429:
                _set_goods_return_token_block(
                    api_key=api_key,
                    retry_after=exc.retry_after,
                    retry_seconds=exc.retry_seconds,
                )
                retry_secs = exc.retry_seconds or _parse_wb_retry_seconds(exc.retry_after)
                _log.warning(
                    "goods-return HTTP 429 token=%s source_id=%s retry_after=%ss — sync blocked",
                    token_key,
                    source_id,
                    retry_secs,
                )
            raise


def _fetch_goods_return_resilient(
    candidates: list[tuple[str, str]],
    *,
    date_from: str,
    date_to: str,
    source_id: int | None = None,
) -> tuple[list[dict[str, Any]], str, str]:
    """Try each Analytics-capable key; skip 403 scope errors."""
    last_exc: RuntimeError | None = None
    for key, label in candidates:
        try:
            rows = fetch_goods_return_report_rated(
                api_key=key,
                date_from=date_from,
                date_to=date_to,
                source_id=source_id,
            )
            return rows, key, label
        except RuntimeError as exc:
            if wb.is_goods_return_scope_error(exc):
                last_exc = exc
                continue
            raise
    if last_exc is not None:
        raise last_exc
    return [], "", ""


def _load_source_goods_return_matchers(
    repo: ReviewRepository,
    *,
    user_id: int,
    source_id: int,
) -> dict[str, set[int] | set[str]]:
    """Order/nm/barcodes known for one FBS source (from synced wb_fbs_orders)."""
    wb.ensure_wb_fbs_tables(repo)
    order_ids: set[int] = set()
    nm_ids: set[int] = set()
    barcodes: set[str] = set()
    with repo._connect() as conn:
        rows = conn.execute(
            repo._sql(
                """
                SELECT DISTINCT order_id, nm_id, skus_json
                FROM wb_fbs_orders
                WHERE user_id = ? AND source_id = ?
                """
            ),
            (user_id, source_id),
        ).fetchall()
    for row in rows:
        d = repo._row_to_dict(row)
        try:
            oid = int(d.get("order_id") or 0)
        except (TypeError, ValueError):
            oid = 0
        if oid > 0:
            order_ids.add(oid)
        try:
            nm = int(d.get("nm_id") or 0)
        except (TypeError, ValueError):
            nm = 0
        if nm > 0:
            nm_ids.add(nm)
        try:
            parsed = json.loads(str(d.get("skus_json") or "[]") or "[]")
        except json.JSONDecodeError:
            parsed = []
        if isinstance(parsed, list):
            for sku in parsed:
                code = str(sku or "").strip()
                if code:
                    barcodes.add(code)
    return {"order_ids": order_ids, "nm_ids": nm_ids, "barcodes": barcodes}


def _goods_return_row_matches_source(
    *,
    order_id: int,
    srid: str,
    nm_id: int | None,
    barcode: str = "",
    sticker_id: str = "",
    matchers: dict[str, set[int] | set[str]],
    srid_to_order: dict[str, int],
    confirmed_order_ids: set[int] | None = None,
    trust_report: bool = False,
) -> bool:
    """True when a goods-return row belongs to the selected FBS source."""
    if trust_report:
        return _goods_return_row_has_identity(
            order_id=order_id,
            srid=srid,
            sticker_id=sticker_id,
            nm_id=nm_id,
        )

    if order_id > 0:
        if order_id in matchers["order_ids"]:
            return True
        if confirmed_order_ids and order_id in confirmed_order_ids:
            return True
        return False

    srid_key = str(srid or "").strip()
    if srid_key:
        mapped = int(srid_to_order.get(srid_key) or 0)
        if mapped > 0:
            if mapped in matchers["order_ids"]:
                return True
            if confirmed_order_ids and mapped in confirmed_order_ids:
                return True
            return False
    bc = str(barcode or "").strip()
    if bc and bc in matchers.get("barcodes", set()):
        return True
    if nm_id and int(nm_id) > 0:
        return int(nm_id) in matchers["nm_ids"]
    return False


