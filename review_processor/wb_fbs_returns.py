def list_return_scans(
    repo: ReviewRepository,
    *,
    user_id: int,
    source_id: int,
    date_from: str = "",
    date_to: str = "",
    search: str = "",
    scan_types: list[str] | None = None,
    limit: int = 50,
    offset: int = 0,
) -> dict[str, Any]:
    ensure_wb_fbs_returns_tables(repo)
    clauses = ["user_id = ?", "source_id = ?"]
    params: list[Any] = [user_id, source_id]
    df = _parse_iso_date(date_from)
    dt = _parse_iso_date(date_to)
    if df:
        clauses.append("scanned_at >= ?")
        params.append(f"{df}T00:00:00+00:00")
    if dt:
        clauses.append("scanned_at < ?")
        end = date.fromisoformat(dt) + timedelta(days=1)
        params.append(f"{end.isoformat()}T00:00:00+00:00")
    if scan_types:
        placeholders = ",".join("?" for _ in scan_types)
        clauses.append(f"scan_type IN ({placeholders})")
        params.extend(scan_types)
    search_clause, search_params = _return_scans_search_sql(search)
    if search_clause:
        clauses.append(search_clause)
        params.extend(search_params)
    page_limit = max(1, min(int(limit), 2000))
    page_offset = max(0, int(offset))
    fetch_limit = page_limit + 1
    sql = (
        "SELECT * FROM wb_fbs_return_scans WHERE "
        + " AND ".join(clauses)
        + " ORDER BY scanned_at DESC LIMIT ? OFFSET ?"
    )
    params.extend([fetch_limit, page_offset])
    with repo._connect() as conn:
        rows = conn.execute(repo._sql(sql), tuple(params)).fetchall()
    has_more = len(rows) > page_limit
    if has_more:
        rows = rows[:page_limit]
    items = [_scan_row_to_api(repo._row_to_dict(r)) for r in rows]
    by_article = _catalog_by_article_index(repo, user_id=user_id)
    for item in items:
        _enrich_return_scan_catalog_fields(
            repo,
            user_id=user_id,
            item=item,
            by_article=by_article,
        )
    return {"items": items, "has_more": has_more}


def _goods_return_srid_hint(
    repo: ReviewRepository,
    *,
    user_id: int,
    source_id: int,
    order_id: int,
) -> str:
    ensure_wb_fbs_returns_tables(repo)
    with repo._connect() as conn:
        row = conn.execute(
            repo._sql(
                """
                SELECT srid FROM wb_fbs_goods_returns
                WHERE user_id = ? AND source_id = ? AND wb_order_id = ?
                  AND srid <> ''
                ORDER BY synced_at DESC
                LIMIT 1
                """
            ),
            (user_id, source_id, int(order_id)),
        ).fetchone()
    if not row:
        return ""
    return str(repo._row_to_dict(row).get("srid") or "").strip()


