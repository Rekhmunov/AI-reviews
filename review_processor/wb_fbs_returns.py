def process_return_scan(
    repo: ReviewRepository,
    *,
    user_id: int,
    source_id: int,
    api_key: str,
    scan: str,
) -> dict[str, Any]:
    """Classify scan, resolve order/product/KIZ, persist journal row."""
    scan_text = str(scan or "").strip()
    if not scan_text:
        return {"ok": False, "error": "empty_scan", "message": "Пустое сканирование"}

    if kiz_restore.looks_like_kiz_scan(scan_text):
        return _process_kiz_scan(
            repo,
            user_id=user_id,
            source_id=source_id,
            api_key=api_key,
            scan=scan_text,
        )

    goods_hit = find_goods_return_by_scan(
        repo, user_id=user_id, source_id=source_id, scan=scan_text
    )
    if goods_hit:
        return _process_return_sticker_scan(
            repo,
            user_id=user_id,
            source_id=source_id,
            api_key=api_key,
            scan=scan_text,
            goods_row=goods_hit,
        )

    sticker_hit = kiz_restore.find_orders_by_sticker_scan(
        repo, user_id=user_id, source_id=source_id, scan=scan_text
    )
    if sticker_hit.get("ambiguous"):
        ids = [
            int(r.get("order_id"))
            for r in (sticker_hit.get("matches") or [])
            if r.get("order_id") is not None
        ]
        return {
            "ok": False,
            "error": "ambiguous_sticker",
            "message": "Стикер совпадает у нескольких заказов",
            "order_ids": ids[:10],
        }
    if sticker_hit.get("row"):
        return _process_assembly_sticker_scan(
            repo,
            user_id=user_id,
            source_id=source_id,
            api_key=api_key,
            scan=scan_text,
            order_row=sticker_hit["row"],
        )

    return {
        "ok": False,
        "error": "not_found",
        "message": "Не удалось распознать скан. Синхронизируйте возвраты WB или проверьте сканирование.",
    }


_RESTORE_NOT_FOUND_MSG = (
    "Не найдено в уже загруженных отчётах. "
    "Сначала синхронизируйте в «ВБ ФБС → Возвраты → Синхр. WB», затем повторите скан."
)
_RESTORE_AMBIGUOUS_MSG = "Найдено в нескольких кабинетах — уточните скан или источник"
_RESTORE_DUPLICATE_MSG = "Уже был в журнале — можно распечатать снова"


def _restore_source_meta(source: Mapping[str, Any] | dict[str, Any]) -> dict[str, Any]:
    try:
        sid = int(source.get("id") or source.get("source_id") or 0)
    except (TypeError, ValueError):
        sid = 0
    return {
        "source_id": sid,
        "source_name": str(source.get("name") or "").strip(),
    }


def _goods_return_identity(row: dict[str, Any]) -> tuple[str, str]:
    try:
        order_id = int(row.get("wb_order_id") or 0)
    except (TypeError, ValueError):
        order_id = 0
    if order_id > 0:
        return ("order", str(order_id))
    sticker = str(row.get("sticker_id") or "").strip()
    if sticker:
        return ("sticker", sticker)
    srid = str(row.get("srid") or "").strip()
    if srid:
        return ("srid", srid)
    barcode = str(row.get("barcode") or row.get("shk_id") or "").strip()
    if barcode:
        return ("barcode", barcode)
    return ("row", str(row.get("id") or ""))


def _attach_restore_lookup_details(
    repo: ReviewRepository,
    *,
    user_id: int,
    source_id: int,
    item: dict[str, Any],
) -> dict[str, Any]:
    """Attach WB/Ozon lookup detail card fields (local DB only, no remote)."""
    if not isinstance(item, dict):
        return item
    if str(item.get("scan_type") or "").strip() == SCAN_CATALOG:
        return item
    if isinstance(item.get("details"), dict) and item.get("details"):
        return item

    marketplace = str(item.get("marketplace") or "").strip().lower()
    posting_number = str(item.get("posting_number") or "").strip()
    if marketplace == "ozon" or posting_number:
        from . import ozon_fbs as oz

        sid = int(source_id or 0)
        pn = posting_number or str(item.get("order_id") or "").strip()
        row = None
        if pn and sid > 0:
            try:
                row = oz.get_posting_by_number(
                    repo, user_id=user_id, source_id=sid, posting_number=pn
                )
            except Exception:
                row = None
        if isinstance(row, dict) and row:
            try:
                item["details"] = oz.build_posting_lookup_details(
                    repo,
                    user_id=user_id,
                    source_id=sid,
                    row=row,
                    remote=None,
                    client=None,
                )
            except Exception as exc:
                _log.debug("restore ozon lookup details: %s", exc)
        return item

    try:
        order_id = int(item.get("order_id") or 0)
    except (TypeError, ValueError):
        order_id = 0
    if order_id <= 0:
        return item
    sid = int(source_id or 0)
    row = None
    if sid > 0:
        try:
            row = wb.get_order_by_id(
                repo, user_id=user_id, source_id=sid, order_id=order_id
            )
        except Exception:
            row = None
    if not row:
        try:
            row = _find_local_order_any_source(
                repo,
                user_id=user_id,
                order_id=order_id,
                prefer_source_id=sid,
            )
        except Exception:
            row = None
    if not isinstance(row, dict) or not row:
        return item
    try:
        row_sid = int(row.get("source_id") or sid or 0)
    except (TypeError, ValueError):
        row_sid = sid
    try:
        enriched = wb._enrich_order_row(repo, user_id=user_id, row=row)
    except Exception:
        enriched = dict(row)
    try:
        item["details"] = wb.build_order_lookup_details(
            repo,
            user_id=user_id,
            source_id=row_sid or sid,
            row=enriched,
        )
    except Exception as exc:
        _log.debug("restore wb lookup details: %s", exc)
    return item


def _finalize_restore_scan_result(
    result: dict[str, Any],
    *,
    source: Mapping[str, Any] | dict[str, Any],
    repo: ReviewRepository | None = None,
    user_id: int = 0,
) -> dict[str, Any]:
    meta = _restore_source_meta(source)
    if result.get("ok"):
        item = result.get("item") if isinstance(result.get("item"), dict) else {}
        if repo is not None and user_id and isinstance(item, dict):
            item = _attach_restore_lookup_details(
                repo,
                user_id=int(user_id),
                source_id=int(meta["source_id"] or 0),
                item=item,
            )
        _log.info(
            "restore_scan hit source_id=%s order_id=%s scan_type=%s",
            meta["source_id"],
            item.get("order_id"),
            item.get("scan_type"),
        )
        return {
            "ok": True,
            "duplicate": False,
            "item": item,
            "source_id": meta["source_id"],
            "source_name": meta["source_name"],
        }
    if str(result.get("error") or "") == "duplicate":
        item = result.get("item") if isinstance(result.get("item"), dict) else {}
        if repo is not None and user_id and isinstance(item, dict):
            item = _attach_restore_lookup_details(
                repo,
                user_id=int(user_id),
                source_id=int(meta["source_id"] or 0),
                item=item,
            )
        _log.info(
            "restore_scan duplicate source_id=%s scan_id=%s",
            meta["source_id"],
            item.get("id"),
        )
        return {
            "ok": True,
            "duplicate": True,
            "item": item,
            "source_id": meta["source_id"],
            "source_name": meta["source_name"],
            "message": _RESTORE_DUPLICATE_MSG,
        }
    return result


def _run_restore_scan_on_source(
    repo: ReviewRepository,
    *,
    user_id: int,
    source: Mapping[str, Any] | dict[str, Any],
    scan: str,
) -> dict[str, Any]:
    """Process scan on one source using local DB only (empty api_key)."""
    meta = _restore_source_meta(source)
    sid = int(meta["source_id"] or 0)
    if sid <= 0:
        return {
            "ok": False,
            "error": "invalid_source",
            "message": "Некорректный источник",
        }
    result = process_return_scan(
        repo,
        user_id=user_id,
        source_id=sid,
        api_key="",
        scan=scan,
    )
    return _finalize_restore_scan_result(
        result, source=source, repo=repo, user_id=user_id
    )


def _process_restore_kiz_scan(
    repo: ReviewRepository,
    *,
    user_id: int,
    sources: list[Mapping[str, Any] | dict[str, Any]],
    scan: str,
) -> dict[str, Any]:
    code = kiz_restore.normalize_kiz_mark(scan)
    hits: list[tuple[Mapping[str, Any] | dict[str, Any], list[int]]] = []
    order_ids: set[int] = set()
    for source in sources:
        meta = _restore_source_meta(source)
        sid = int(meta["source_id"] or 0)
        if sid <= 0:
            continue
        db_hit = kiz_restore.find_kiz_in_local_database(
            repo, user_id=user_id, source_id=sid, kiz_code=code
        )
        if not db_hit.get("found"):
            continue
        matched = [int(x) for x in (db_hit.get("order_ids") or []) if int(x) > 0]
        if not matched:
            continue
        hits.append((source, matched))
        order_ids.update(matched)

    if len(order_ids) > 1:
        _log.info("restore_scan ambiguous_kiz orders=%s", sorted(order_ids)[:10])
        return {
            "ok": False,
            "error": "ambiguous",
            "message": _RESTORE_AMBIGUOUS_MSG,
            "order_ids": sorted(order_ids)[:10],
        }

    if hits:
        return _run_restore_scan_on_source(
            repo, user_id=user_id, source=hits[0][0], scan=scan
        )

    # No local order link — still allow reprint (same as admin KIZ path warnings).
    return _run_restore_scan_on_source(
        repo, user_id=user_id, source=sources[0], scan=scan
    )


def _looks_like_wb_order_id_scan(scan: str) -> bool:
    """Pure numeric assembly order id (≥6 digits), not a KIZ payload."""
    text = str(scan or "").strip().replace(" ", "")
    return bool(re.fullmatch(r"\d{6,}", text))


def _product_fields_from_catalog_product(product: Mapping[str, Any] | dict[str, Any] | None) -> dict[str, Any]:
    if not product:
        return {}
    article = str(product.get("supplier_article") or "").strip()
    name = str(product.get("name") or "").strip() or article
    barcodes = [
        str(b or "").strip()
        for b in (product.get("barcodes") or [])
        if str(b or "").strip()
    ]
    photo = ""
    pid = int(product.get("id") or 0)
    if pid and product.get("photo_path"):
        photo = f"/api/products/photo/{pid}"
    catalog_fields = _catalog_fields_from_product(dict(product))
    return {
        "product_name": name,
        "product_article": article,
        "product_photo": photo,
        "product_barcodes": list(barcodes),
        **catalog_fields,
    }


def _build_restore_order_item(
    repo: ReviewRepository,
    *,
    user_id: int,
    source_id: int,
    order_row: dict[str, Any],
    scan: str,
    scan_type: str = SCAN_LOOKUP,
) -> dict[str, Any]:
    """Ephemeral restore card from a local WB FBS order (not written to journal)."""
    try:
        order_id = int(order_row.get("order_id") or 0)
    except (TypeError, ValueError):
        order_id = 0
    product = _product_from_order(repo, user_id=user_id, order_row=order_row)
    srid_hint = ""
    if order_id > 0 and source_id > 0:
        try:
            srid_hint = _goods_return_srid_hint(
                repo, user_id=user_id, source_id=source_id, order_id=order_id
            )
        except Exception:
            srid_hint = ""
    kiz_codes = (
        _kiz_codes_for_order(
            repo,
            user_id=user_id,
            source_id=source_id,
            order_id=order_id,
            api_key="",
            order_row=order_row,
            srid_hint=srid_hint,
        )
        if order_id > 0 and source_id > 0
        else []
    )
    kiz_code = kiz_codes[0] if kiz_codes else ""
    part_a = str(order_row.get("sticker_part_a") or "").strip()
    part_b = str(order_row.get("sticker_part_b") or "").strip()
    item = {
        "id": None,
        "preview": True,
        "scan_type": scan_type,
        "scanned_at": "",
        "scan_raw": str(scan or "").strip(),
        "return_sticker_id": "",
        "order_id": order_id if order_id > 0 else None,
        "assembly_sticker_barcode": str(order_row.get("sticker_barcode") or "").strip(),
        "assembly_sticker_number": kiz_restore.sticker_number(part_a, part_b),
        "kiz_code": kiz_code,
        "matched_order_ids": [order_id] if order_id > 0 else [],
        "gtin14": kiz_restore.extract_gtin14(kiz_code) if kiz_code else "",
        **product,
    }
    return _enrich_return_scan_catalog_fields(repo, user_id=user_id, item=item)


def _restore_scan_wb_order_id(
    repo: ReviewRepository,
    *,
    user_id: int,
    sources: list[Mapping[str, Any] | dict[str, Any]],
    scan: str,
) -> dict[str, Any] | None:
    if not _looks_like_wb_order_id_scan(scan):
        return None
    try:
        order_id = int(str(scan).strip().replace(" ", ""))
    except (TypeError, ValueError):
        return None
    by_order: dict[int, tuple[Mapping[str, Any] | dict[str, Any], dict[str, Any]]] = {}
    for source in sources:
        meta = _restore_source_meta(source)
        sid = int(meta["source_id"] or 0)
        if sid <= 0:
            continue
        row = wb.get_order_by_id(
            repo, user_id=user_id, source_id=sid, order_id=order_id
        )
        if not row:
            continue
        by_order[order_id] = (source, row)
        break
    if not by_order:
        row = _find_local_order_any_source(
            repo, user_id=user_id, order_id=order_id, prefer_source_id=0
        )
        if not row:
            return None
        try:
            sid = int(row.get("source_id") or 0)
        except (TypeError, ValueError):
            sid = 0
        source = next(
            (
                s
                for s in sources
                if int(_restore_source_meta(s)["source_id"] or 0) == sid
            ),
            {"id": sid, "name": f"WB FBS #{sid}" if sid else "WB FBS"},
        )
        by_order[order_id] = (source, row)
    source, order_row = next(iter(by_order.values()))
    meta = _restore_source_meta(source)
    item = _build_restore_order_item(
        repo,
        user_id=user_id,
        source_id=int(meta["source_id"] or 0),
        order_row=order_row,
        scan=scan,
        scan_type=SCAN_LOOKUP,
    )
    if not item.get("kiz_code") and item.get("order_id"):
        item["warning"] = (
            f"Для заказа {item['order_id']} не найден КИЗ "
            "(маркировка, «Вывод КИЗ» или WB meta)"
        )
    return _finalize_restore_scan_result(
        {"ok": True, "item": item},
        source=source,
        repo=repo,
        user_id=user_id,
    )


