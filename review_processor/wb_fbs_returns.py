def _confirm_order_ids_on_marketplace(
    marketplace_api_key: str,
    order_ids: list[int],
) -> set[int]:
    """Order IDs that exist on this seller cabinet (POST /api/v3/orders/status)."""
    ids = sorted({int(x) for x in order_ids if int(x) > 0})
    if not ids or not str(marketplace_api_key or "").strip():
        return set()
    client = wb.WbFbsClient(str(marketplace_api_key).strip())
    confirmed: set[int] = set()
    for i in range(0, len(ids), GOODS_RETURN_STATUS_BATCH):
        chunk = ids[i : i + GOODS_RETURN_STATUS_BATCH]
        try:
            statuses = client.get_statuses(chunk)
        except Exception as exc:
            _log.warning("goods-return order status batch failed: %s", exc)
            continue
        for st in statuses or []:
            if not isinstance(st, dict):
                continue
            try:
                oid = int(st.get("id") or 0)
            except (TypeError, ValueError):
                continue
            if oid > 0:
                confirmed.add(oid)
    return confirmed


def _hydrate_confirmed_return_orders(
    repo: ReviewRepository,
    *,
    user_id: int,
    source_id: int,
    order_ids: set[int],
    known_order_ids: set[int],
    api_key: str,
    limit: int = GOODS_RETURN_HYDRATE_CONFIRMED_LIMIT,
) -> int:
    """Pull minimal order rows for confirmed return orderIds missing locally."""
    missing = sorted({int(x) for x in order_ids if int(x) > 0 and int(x) not in known_order_ids})
    if not missing or not str(api_key or "").strip():
        return 0
    client = wb.WbFbsClient(str(api_key).strip())
    hydrated = 0
    for oid in missing[: max(0, int(limit))]:
        try:
            payload, is_archive, status = wb._fetch_order_payload_from_wb(
                client, oid, max_archive_pages=12
            )
        except Exception as exc:
            _log.warning("returns hydrate confirmed order %s failed: %s", oid, exc)
            continue
        if not payload:
            continue
        ss = str((status or {}).get("supplierStatus") or payload.get("supplierStatus") or "")
        ws = str((status or {}).get("wbStatus") or payload.get("wbStatus") or "")
        wb.upsert_order(
            repo,
            user_id=user_id,
            source_id=source_id,
            order=payload,
            supplier_status=ss,
            wb_status=ws,
            is_archive=is_archive,
        )
        hydrated += 1
    return hydrated


