def _catalog_fields_from_product(product: dict[str, Any] | None) -> dict[str, Any]:
    if not product:
        return {
            "catalog_barcodes": [],
            "barcode_label_name": "",
        }
    barcodes = [
        str(b or "").strip()
        for b in (product.get("barcodes") or [])
        if str(b or "").strip()
    ]
    return {
        "catalog_barcodes": barcodes,
        "barcode_label_name": str(product.get("barcode_label_name") or "").strip(),
    }


def _product_from_order(
    repo: ReviewRepository,
    *,
    user_id: int,
    order_row: dict[str, Any] | None,
) -> dict[str, Any]:
    if not order_row:
        return {}
    article = str(order_row.get("article") or "").strip()
    nm_id = str(order_row.get("nm_id") or "").strip()
    name_map = repo.get_product_name_by_article(user_id=user_id)
    photo_map = repo.get_product_photo_map(user_id=user_id)
    name = (
        name_map.get(article)
        or name_map.get(article.casefold())
        or name_map.get(nm_id)
        or name_map.get(nm_id.casefold())
        or ""
    )
    photo = photo_map.get(article) or photo_map.get(nm_id) or ""
    barcodes: list[str] = []
    try:
        parsed = json.loads(order_row.get("skus_json") or "[]")
        if isinstance(parsed, list):
            barcodes = [str(x).strip() for x in parsed if str(x or "").strip()]
    except Exception:
        pass
    catalog = _catalog_barcodes_index(repo, user_id=user_id)
    for p in repo.list_product_photos(user_id=user_id):
        if article and str(p.get("supplier_article") or "").strip() == article:
            for b in p.get("barcodes") or []:
                text = str(b or "").strip()
                if text and text not in barcodes:
                    barcodes.append(text)
            break
        if nm_id and str(p.get("wb_nmid") or "").strip() == nm_id:
            for b in p.get("barcodes") or []:
                text = str(b or "").strip()
                if text and text not in barcodes:
                    barcodes.append(text)
            break
    catalog_product = _catalog_product_for_order(
        repo, user_id=user_id, order_row=order_row
    )
    catalog_fields = _catalog_fields_from_product(catalog_product)
    return {
        "product_name": name,
        "product_article": article,
        "product_photo": photo,
        "product_barcodes": barcodes,
        **catalog_fields,
    }


def _product_from_gtin(
    repo: ReviewRepository,
    *,
    user_id: int,
    gtin14: str,
) -> dict[str, Any]:
    if not gtin14:
        return {}
    catalog = _catalog_barcodes_index(repo, user_id=user_id)
    p = catalog.get(gtin14) or catalog.get(gtin14.lstrip("0")) or catalog.get(_digits_only(gtin14))
    if not p:
        return {}
    pid = int(p.get("id") or 0)
    photo = f"/api/products/photo/{pid}" if pid and p.get("photo_path") else ""
    return {
        "product_name": str(p.get("name") or "").strip(),
        "product_article": str(p.get("supplier_article") or "").strip(),
        "product_photo": photo,
        "product_barcodes": list(p.get("barcodes") or []),
        **_catalog_fields_from_product(p),
    }


