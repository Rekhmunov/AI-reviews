def _scan_row_to_api(row: dict[str, Any]) -> dict[str, Any]:
    if not row:
        return {}
    out = dict(row)
    try:
        out["matched_order_ids"] = json.loads(out.pop("matched_order_ids_json", "[]") or "[]")
    except Exception:
        out["matched_order_ids"] = []
    try:
        out["product_barcodes"] = json.loads(out.pop("product_barcodes_json", "[]") or "[]")
    except Exception:
        out["product_barcodes"] = []
    out.pop("product_barcodes_json", None)
    out.pop("matched_order_ids_json", None)
    return out


def process_return_scan(
    repo: ReviewRepository,
    *,
    user_id: int,
    source_id: int,
    api_key: str,
    scan: str,
) -> dict[str, Any]:
    """Classify scan, resolve order/product/KIZ, persist journal row."""
    scan_text = str(scan or "").strip()
    if not scan_text:
        return {"ok": False, "error": "empty_scan", "message": "Пустое сканирование"}

    if kiz_restore.looks_like_kiz_scan(scan_text):
        return _process_kiz_scan(
            repo,
            user_id=user_id,
            source_id=source_id,
            api_key=api_key,
            scan=scan_text,
        )

    goods_hit = find_goods_return_by_scan(
        repo, user_id=user_id, source_id=source_id, scan=scan_text
    )
    if goods_hit:
        return _process_return_sticker_scan(
            repo,
            user_id=user_id,
            source_id=source_id,
            api_key=api_key,
            scan=scan_text,
            goods_row=goods_hit,
        )

    sticker_hit = kiz_restore.find_orders_by_sticker_scan(
        repo, user_id=user_id, source_id=source_id, scan=scan_text
    )
    if sticker_hit.get("ambiguous"):
        ids = [
            int(r.get("order_id"))
            for r in (sticker_hit.get("matches") or [])
            if r.get("order_id") is not None
        ]
        return {
            "ok": False,
            "error": "ambiguous_sticker",
            "message": "Стикер совпадает у нескольких заказов",
            "order_ids": ids[:10],
        }
    if sticker_hit.get("row"):
        return _process_assembly_sticker_scan(
            repo,
            user_id=user_id,
            source_id=source_id,
            api_key=api_key,
            scan=scan_text,
            order_row=sticker_hit["row"],
        )

    return {
        "ok": False,
        "error": "not_found",
        "message": "Не удалось распознать скан. Синхронизируйте возвраты WB или проверьте сканирование.",
    }


def _process_return_sticker_scan(
    repo: ReviewRepository,
    *,
    user_id: int,
    source_id: int,
    api_key: str,
    scan: str,
    goods_row: dict[str, Any],
) -> dict[str, Any]:
    sticker_id = str(goods_row.get("sticker_id") or "").strip() or _digits_only(scan)
    dup = _return_scan_duplicate(
        repo, user_id=user_id, source_id=source_id, return_sticker_id=sticker_id
    )
    if dup:
        return {
            "ok": False,
            "error": "duplicate",
            "message": "Этот стикер возврата уже просканирован",
            "item": _scan_row_to_api(dup),
        }
    try:
        order_id = int(goods_row.get("wb_order_id") or 0)
    except (TypeError, ValueError):
        order_id = 0
    srid_hint = str(goods_row.get("srid") or "").strip()
    order_row = (
        _resolve_order_row(
            repo,
            user_id=user_id,
            source_id=source_id,
            order_id=order_id,
            api_key=api_key,
        )
        if order_id > 0
        else None
    )
    product = _product_from_order(repo, user_id=user_id, order_row=order_row)
    kiz_codes = (
        _kiz_codes_for_order(
            repo,
            user_id=user_id,
            source_id=source_id,
            order_id=order_id,
            api_key=api_key,
            order_row=order_row,
            srid_hint=srid_hint,
        )
        if order_id > 0
        else []
    )
    kiz_code = kiz_codes[0] if kiz_codes else ""
    assembly_number = ""
    assembly_barcode = ""
    if order_row:
        part_a = str(order_row.get("sticker_part_a") or "").strip()
        part_b = str(order_row.get("sticker_part_b") or "").strip()
        assembly_number = kiz_restore.sticker_number(part_a, part_b)
        assembly_barcode = str(order_row.get("sticker_barcode") or "").strip()
    item = _insert_return_scan(
        repo,
        user_id=user_id,
        source_id=source_id,
        payload={
            "scan_type": SCAN_RETURN,
            "scan_raw": scan,
            "return_sticker_id": sticker_id,
            "order_id": order_id if order_id > 0 else None,
            "assembly_sticker_barcode": assembly_barcode,
            "assembly_sticker_number": assembly_number,
            "kiz_code": kiz_code,
            "matched_order_ids": [order_id] if order_id > 0 else [],
            "gtin14": kiz_restore.extract_gtin14(kiz_code) if kiz_code else "",
            **product,
        },
    )
    if not kiz_code and order_id > 0:
        item["warning"] = (
            f"Для заказа {order_id} не найден КИЗ "
            "(маркировка, WB meta или «Вывод КИЗ»)"
        )
    return {"ok": True, "item": item}


def _process_assembly_sticker_scan(
    repo: ReviewRepository,
    *,
    user_id: int,
    source_id: int,
    api_key: str,
    scan: str,
    order_row: dict[str, Any],
) -> dict[str, Any]:
    try:
        order_id = int(order_row.get("order_id"))
    except (TypeError, ValueError, KeyError):
        return {"ok": False, "error": "not_found", "message": "Некорректный заказ"}
    resolved_order = _resolve_order_row(
        repo,
        user_id=user_id,
        source_id=source_id,
        order_id=order_id,
        api_key=api_key,
    ) or order_row
    wb.persist_order_stickers_batch(
        repo,
        user_id=user_id,
        source_id=source_id,
        stickers={
            order_id: {
                "sticker_barcode": kiz_restore.normalize_sticker_scan(scan),
                "sticker_part_a": str(resolved_order.get("sticker_part_a") or "").strip(),
                "sticker_part_b": str(resolved_order.get("sticker_part_b") or "").strip(),
            }
        },
    )
    product = _product_from_order(repo, user_id=user_id, order_row=resolved_order)
    kiz_codes = _kiz_codes_for_order(
        repo,
        user_id=user_id,
        source_id=source_id,
        order_id=order_id,
        api_key=api_key,
        order_row=resolved_order,
    )
    kiz_code = kiz_codes[0] if kiz_codes else ""
    part_a = str(resolved_order.get("sticker_part_a") or "").strip()
    part_b = str(resolved_order.get("sticker_part_b") or "").strip()
    item = _insert_return_scan(
        repo,
        user_id=user_id,
        source_id=source_id,
        payload={
            "scan_type": SCAN_ASSEMBLY,
            "scan_raw": scan,
            "order_id": order_id,
            "assembly_sticker_barcode": kiz_restore.normalize_sticker_scan(scan),
            "assembly_sticker_number": kiz_restore.sticker_number(part_a, part_b),
            "kiz_code": kiz_code,
            "matched_order_ids": [order_id],
            "gtin14": kiz_restore.extract_gtin14(kiz_code) if kiz_code else "",
            **product,
        },
    )
    return {"ok": True, "item": item}


def _process_kiz_scan(
    repo: ReviewRepository,
    *,
    user_id: int,
    source_id: int,
    api_key: str,
    scan: str,
) -> dict[str, Any]:
    code = kiz_restore.normalize_kiz_mark(scan)
    gtin14 = kiz_restore.extract_gtin14(code)
    db_hit = kiz_restore.find_kiz_in_local_database(
        repo, user_id=user_id, source_id=source_id, kiz_code=code
    )
    matched_ids = [int(x) for x in (db_hit.get("order_ids") or [])]
    order_id: int | None = matched_ids[0] if len(matched_ids) == 1 else None
    order_row = (
        _resolve_order_row(
            repo,
            user_id=user_id,
            source_id=source_id,
            order_id=int(order_id),
            api_key=api_key,
        )
        if order_id
        else None
    )
    product = (
        _product_from_order(repo, user_id=user_id, order_row=order_row)
        if order_row
        else _product_from_gtin(repo, user_id=user_id, gtin14=gtin14)
    )
    gtin_warning = ""
    if gtin14:
        catalog = _catalog_barcodes_index(repo, user_id=user_id)
        gtin_digits = _digits_only(gtin14)
        in_catalog = (
            gtin14 in catalog
            or gtin14.lstrip("0") in catalog
            or gtin_digits in catalog
        )
        if not in_catalog:
            gtin_warning = "GTIN не найден в каталоге товаров"
    assembly_number = ""
    assembly_barcode = ""
    if order_row:
        part_a = str(order_row.get("sticker_part_a") or "").strip()
        part_b = str(order_row.get("sticker_part_b") or "").strip()
        assembly_number = kiz_restore.sticker_number(part_a, part_b)
        assembly_barcode = str(order_row.get("sticker_barcode") or "").strip()
    item = _insert_return_scan(
        repo,
        user_id=user_id,
        source_id=source_id,
        payload={
            "scan_type": SCAN_KIZ,
            "scan_raw": scan,
            "order_id": order_id,
            "assembly_sticker_barcode": assembly_barcode,
            "assembly_sticker_number": assembly_number,
            "kiz_code": code,
            "matched_order_ids": matched_ids,
            "gtin14": gtin14,
            **product,
        },
    )
    if len(matched_ids) > 1:
        item["warning"] = (
            f"КИЗ найден у заказов: {', '.join(str(x) for x in matched_ids[:5])}"
            f"{'…' if len(matched_ids) > 5 else ''}"
        )
    elif not db_hit.get("found"):
        item["warning"] = "КИЗ не найден в локальной базе заказов"
    if gtin_warning:
        item["warning"] = (
            f"{item['warning']} · {gtin_warning}"
            if item.get("warning")
            else gtin_warning
        )
    return {"ok": True, "item": item}


