_goods_return_sync_lock_guard = threading.Lock()
_goods_return_sync_locks: dict[str, threading.Lock] = {}

_goods_return_job_guard = threading.Lock()
_goods_return_jobs: dict[str, dict[str, Any]] = {}


def _goods_return_job_key(*, user_id: int, source_id: int) -> str:
    return f"wb-goods-return-job:{int(user_id)}:{int(source_id)}"


def get_goods_return_sync_job(
    *,
    user_id: int,
    source_id: int,
) -> dict[str, Any] | None:
    key = _goods_return_job_key(user_id=user_id, source_id=source_id)
    with _goods_return_job_guard:
        job = _goods_return_jobs.get(key)
        return dict(job) if isinstance(job, dict) else None


def start_goods_return_sync_async(
    *,
    user_id: int,
    source_id: int,
    sync_callable,
) -> dict[str, Any]:
    """Run ``sync_callable()`` in a daemon thread; return job handle for polling."""
    key = _goods_return_job_key(user_id=user_id, source_id=source_id)
    with _goods_return_job_guard:
        existing = _goods_return_jobs.get(key)
        if isinstance(existing, dict) and str(existing.get("status") or "") == "running":
            return {
                "ok": True,
                "async": True,
                "status": "running",
                "already_running": True,
                "source_id": int(source_id),
                "started_at": existing.get("started_at"),
                "message": (
                    "Синхронизация возвратов WB уже выполняется для этого источника. "
                    "Дождитесь завершения (~2 мин для 90 дней)."
                ),
            }
        started_at = datetime.now(UTC).isoformat()
        _goods_return_jobs[key] = {
            "status": "running",
            "source_id": int(source_id),
            "started_at": started_at,
        }

    def _worker() -> None:
        try:
            result = sync_callable()
            with _goods_return_job_guard:
                _goods_return_jobs[key] = {
                    "status": "ok",
                    "source_id": int(source_id),
                    "started_at": started_at,
                    "finished_at": datetime.now(UTC).isoformat(),
                    "result": result,
                }
        except GoodsReturnSyncInProgress as exc:
            with _goods_return_job_guard:
                _goods_return_jobs[key] = {
                    "status": "error",
                    "source_id": int(source_id),
                    "started_at": started_at,
                    "finished_at": datetime.now(UTC).isoformat(),
                    "error": str(exc),
                }
        except RuntimeError as exc:
            with _goods_return_job_guard:
                _goods_return_jobs[key] = {
                    "status": "error",
                    "source_id": int(source_id),
                    "started_at": started_at,
                    "finished_at": datetime.now(UTC).isoformat(),
                    "error": str(exc),
                }
        except Exception as exc:
            _log.exception("goods-return async sync failed user=%s source=%s", user_id, source_id)
            with _goods_return_job_guard:
                _goods_return_jobs[key] = {
                    "status": "error",
                    "source_id": int(source_id),
                    "started_at": started_at,
                    "finished_at": datetime.now(UTC).isoformat(),
                    "error": str(exc) or "Синхронизация не удалась",
                }

    threading.Thread(
        target=_worker,
        name=f"wb-goods-return-sync-{user_id}-{source_id}",
        daemon=True,
    ).start()
    return {
        "ok": True,
        "async": True,
        "status": "running",
        "already_running": False,
        "source_id": int(source_id),
        "started_at": started_at,
        "message": (
            "Синхронизация возвратов WB запущена в фоне (~2 мин для 90 дней). "
            "Не закрывайте окно — статус обновится автоматически."
        ),
    }


def _goods_return_sync_lock_key(*, user_id: int, cabinet_uid: int | None) -> str:
    uid = int(cabinet_uid or 0)
    return f"wb-goods-return:{int(user_id)}:{uid}"


class GoodsReturnSyncInProgress(RuntimeError):
    """Another goods-return sync is running for this WB seller cabinet."""


@contextlib.contextmanager
def goods_return_sync_lock(*, user_id: int, cabinet_uid: int | None):
    key = _goods_return_sync_lock_key(user_id=user_id, cabinet_uid=cabinet_uid)
    with _goods_return_sync_lock_guard:
        lock = _goods_return_sync_locks.setdefault(key, threading.Lock())
    if not lock.acquire(blocking=False):
        raise GoodsReturnSyncInProgress(
            "Синхронизация возвратов WB для этого кабинета уже выполняется. "
            "Дождитесь завершения или повторите через 1–2 мин."
        )
    try:
        yield
    finally:
        lock.release()


def resolve_goods_return_api_key(
    *,
    source_api_key: str | None,
    source_analytics_api_key: str | None = None,
    fallback_analytics_key: str | None,
) -> tuple[str, str, bool]:
    """Pick WB token for goods-return report.

    goods-return lives on seller-analytics API and requires Analytics/Statistics
    scope. Marketplace-only source tokens get 403. When the global Settings key
    belongs to the same seller (JWT uid), it is used as fallback.

    Returns ``(api_key, api_key_source, trust_report)``.
    """
    ordered, trust = resolve_goods_return_api_keys(
        source_api_key=source_api_key,
        source_analytics_api_key=source_analytics_api_key,
        fallback_analytics_key=fallback_analytics_key,
    )
    key, label = ordered[0]
    return key, label, trust


def resolve_goods_return_api_keys(
    *,
    source_api_key: str | None,
    source_analytics_api_key: str | None = None,
    fallback_analytics_key: str | None,
) -> tuple[list[tuple[str, str]], bool]:
    """Ordered Analytics-capable keys: [(token, label), ...], trust_report."""
    source = str(source_api_key or "").strip()
    source_analytics = str(source_analytics_api_key or "").strip()
    fallback = str(fallback_analytics_key or "").strip()
    source_uid = wb.wb_jwt_uid(source) if source else None

    ordered: list[tuple[str, str]] = []
    seen: set[str] = set()

    def _add(key: str, label: str) -> None:
        if not key or key in seen:
            return
        if not wb.wb_token_has_goods_return_scope(key):
            return
        seen.add(key)
        ordered.append((key, label))

    if source_analytics:
        _add(source_analytics, "source_analytics")
    if source:
        _add(source, "source")
    if fallback:
        fb_uid = wb.wb_jwt_uid(fallback)
        if source_uid is None or fb_uid == source_uid:
            _add(fallback, "settings")

    if not ordered:
        raise RuntimeError(
            _goods_return_key_resolution_error(
                source, fallback, source_uid, has_source_analytics=bool(source_analytics)
            )
        )

    key, _label = ordered[0]
    trust = bool(source_uid and wb.wb_jwt_uid(key) == source_uid)
    return ordered, trust


def _goods_return_key_resolution_error(
    source_key: str,
    fallback_key: str,
    source_uid: int | None,
    *,
    has_source_analytics: bool = False,
) -> str:
    if (
        fallback_key
        and wb.wb_token_has_goods_return_scope(fallback_key)
        and source_uid
        and wb.wb_jwt_uid(fallback_key) not in (None, source_uid)
    ):
        return (
            "Analytics-ключ в Настройках (Честный знак) принадлежит другому кабинету WB. "
            "Обновите API-токен источника с категориями «Маркетплейс» и «Аналитика» "
            "или укажите Analytics-ключ того же кабинета в Настройках → ЧЗ."
        )
    if has_source_analytics:
        return (
            "API-токен источника не имеет категории «Аналитика» или «Статистика». "
            "Создайте в ЛК WB токен с категориями «Маркетплейс» и «Аналитика» "
            "и обновите ключ источника."
        )
    if source_key and not wb.wb_token_has_goods_return_scope(source_key):
        scopes = ", ".join(wb.wb_token_scope_labels(source_key)) or "не определены"
        return (
            "API-ключ источника не имеет категории «Аналитика» или «Статистика» "
            f"(сейчас: {scopes}). Создайте в ЛК WB новый токен с категорией «Аналитика» "
            "и обновите ключ источника."
        )
    return (
        "Не задан подходящий WB API-ключ для отчёта по возвратам "
        "(нужна категория «Аналитика» или «Статистика»)."
    )


