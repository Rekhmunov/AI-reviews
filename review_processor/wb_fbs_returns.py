def _return_scan_duplicate(
    repo: ReviewRepository,
    *,
    user_id: int,
    source_id: int,
    return_sticker_id: str,
) -> dict[str, Any] | None:
    if not return_sticker_id:
        return None
    ensure_wb_fbs_returns_tables(repo)
    with repo._connect() as conn:
        row = conn.execute(
            repo._sql(
                """
                SELECT * FROM wb_fbs_return_scans
                WHERE user_id = ? AND source_id = ?
                  AND scan_type = ?
                  AND return_sticker_id = ?
                ORDER BY scanned_at DESC
                LIMIT 1
                """
            ),
            (user_id, source_id, SCAN_RETURN, return_sticker_id),
        ).fetchone()
    return repo._row_to_dict(row) if row else None


