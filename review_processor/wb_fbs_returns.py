def _purge_foreign_goods_returns_in_range(
    repo: ReviewRepository,
    *,
    user_id: int,
    source_id: int,
    date_from: str,
    date_to: str,
    matchers: dict[str, set[int]],
    srid_to_order: dict[str, int],
    confirmed_order_ids: set[int] | None = None,
    trust_report: bool = False,
    fetched_srids: set[str] | None = None,
    fetched_stickers: set[str] | None = None,
    fetched_order_ids: set[int] | None = None,
) -> int:
    """Remove cached rows stored under source_id that do not belong to it."""
    rows = list_goods_returns(
        repo,
        user_id=user_id,
        source_id=source_id,
        date_from=date_from,
        date_to=date_to,
    )
    pending_srids = sorted(
        {
            str(row.get("srid") or "").strip()
            for row in rows
            if str(row.get("srid") or "").strip()
            and str(row.get("srid") or "").strip() not in srid_to_order
        }
    )
    if pending_srids:
        srid_to_order.update(
            wb.order_ids_by_srids(
                repo,
                user_id=user_id,
                source_id=source_id,
                srids=pending_srids,
            )
        )
    stale_ids: list[int] = []
    for row in rows:
        if _stored_goods_return_matches_source(
            row,
            matchers=matchers,
            srid_to_order=srid_to_order,
            confirmed_order_ids=confirmed_order_ids,
            trust_report=trust_report,
            fetched_srids=fetched_srids,
            fetched_stickers=fetched_stickers,
            fetched_order_ids=fetched_order_ids,
        ):
            continue
        try:
            row_id = int(row.get("id") or 0)
        except (TypeError, ValueError):
            row_id = 0
        if row_id > 0:
            stale_ids.append(row_id)
    if not stale_ids:
        return 0
    with repo._connect() as conn:
        for row_id in stale_ids:
            conn.execute(
                repo._sql(
                    """
                    DELETE FROM wb_fbs_goods_returns
                    WHERE user_id = ? AND source_id = ? AND id = ?
                    """
                ),
                (user_id, source_id, row_id),
            )
    return len(stale_ids)


def sync_goods_returns(
    repo: ReviewRepository,
    *,
    user_id: int,
    source_id: int,
    api_key: str,
    date_from: str,
    date_to: str,
    marketplace_api_key: str | None = None,
    api_key_source: str = "",
    trust_report: bool | None = None,
    api_key_candidates: list[tuple[str, str]] | None = None,
) -> dict[str, Any]:
    """Sync WB goods-return report for one FBS source.

    Rows are stored when they belong to this ``source_id``. With
    ``trust_report=True`` (same WB seller cabinet), all report rows are kept.
    """
    ensure_wb_fbs_returns_tables(repo)
    date_from, date_to, range_clamped = clamp_goods_return_sync_range(date_from, date_to)
    if trust_report is None:
        trust_report = goods_return_report_trusted(api_key_source)
    candidates = list(api_key_candidates or [])
    if not candidates and api_key:
        candidates = [(str(api_key).strip(), str(api_key_source or "source").strip() or "source")]
    matchers = _load_source_goods_return_matchers(
        repo, user_id=user_id, source_id=source_id
    )
    windows = iter_goods_return_windows(date_from, date_to)
    totals = {
        "fetched": 0,
        "inserted": 0,
        "updated": 0,
        "unchanged": 0,
        "skipped_foreign": 0,
        "purged_foreign": 0,
    }
    window_stats: list[dict[str, Any]] = []
    srid_to_order: dict[str, int] = {}
    confirmed_order_ids: set[int] = set()
    fetched_srids: set[str] = set()
    fetched_stickers: set[str] = set()
    fetched_order_ids: set[int] = set()
    mp_key = str(marketplace_api_key or "").strip()
    cabinet_uid = wb.wb_jwt_uid(mp_key) if mp_key else None
    report_key: str | None = None
    report_label = str(api_key_source or "").strip()
    with goods_return_sync_lock(user_id=user_id, cabinet_uid=cabinet_uid):
        for win_index, (win_from, win_to) in enumerate(windows):
            if report_key:
                rows = fetch_goods_return_report_rated(
                    api_key=report_key,
                    date_from=win_from,
                    date_to=win_to,
                    source_id=source_id,
                )
            else:
                rows, report_key, report_label = _fetch_goods_return_resilient(
                    candidates,
                    date_from=win_from,
                    date_to=win_to,
                    source_id=source_id,
                )
                if not report_key:
                    raise RuntimeError(
                        "Не удалось загрузить отчёт WB: нет ключа с категорией «Аналитика»"
                    )
            if win_index == 0 and len(windows) > 1:
                totals["rate_limit_windows"] = len(windows)
            for row in rows:
                srid = str(row.get("srid") or "").strip()
                if srid:
                    fetched_srids.add(srid)
                sticker = str(row.get("stickerId") or "").strip()
                if sticker:
                    fetched_stickers.add(sticker)
                try:
                    oid = int(row.get("orderId") or 0)
                except (TypeError, ValueError):
                    oid = 0
                if oid > 0:
                    fetched_order_ids.add(oid)
            window_order_ids = sorted(
                {
                    int(row.get("orderId") or 0)
                    for row in rows
                    if int(row.get("orderId") or 0) > 0
                }
            )
            if window_order_ids and mp_key:
                confirmed_order_ids.update(
                    _confirm_order_ids_on_marketplace(mp_key, window_order_ids)
                )
                try:
                    _hydrate_confirmed_return_orders(
                        repo,
                        user_id=user_id,
                        source_id=source_id,
                        order_ids=confirmed_order_ids,
                        known_order_ids=set(matchers.get("order_ids") or set()),
                        api_key=mp_key,
                    )
                    matchers = _load_source_goods_return_matchers(
                        repo, user_id=user_id, source_id=source_id
                    )
                except Exception as exc:
                    _log.warning("returns hydrate confirmed orders failed: %s", exc)
            pending_srids = sorted(
                {
                    str(row.get("srid") or "").strip()
                    for row in rows
                    if str(row.get("srid") or "").strip()
                    and str(row.get("srid") or "").strip() not in srid_to_order
                }
            )
            if pending_srids and mp_key:
                try:
                    wb.hydrate_orders_for_kiz_srids(
                        repo,
                        user_id=user_id,
                        source_id=source_id,
                        srids=pending_srids,
                        api_key=mp_key,
                        archive_pages=30,
                        lookback_days=GOODS_RETURN_DEFAULT_TOTAL_DAYS,
                    )
                    matchers = _load_source_goods_return_matchers(
                        repo, user_id=user_id, source_id=source_id
                    )
                except Exception as exc:
                    _log.warning("returns hydrate before sync failed: %s", exc)
            if pending_srids:
                srid_to_order.update(
                    wb.order_ids_by_srids(
                        repo,
                        user_id=user_id,
                        source_id=source_id,
                        srids=pending_srids,
                    )
                )
            now = datetime.now(UTC).isoformat()
            stats = {
                "fetched": len(rows),
                "inserted": 0,
                "updated": 0,
                "unchanged": 0,
                "skipped_foreign": 0,
            }
            with repo._connect() as conn:
                for row in rows:
                    if not _goods_return_api_row_matches_source(
                        row,
                        matchers=matchers,
                        srid_to_order=srid_to_order,
                        confirmed_order_ids=confirmed_order_ids,
                        trust_report=trust_report,
                    ):
                        stats["skipped_foreign"] += 1
                        continue
                    parsed = _goods_return_values_from_row(
                        row,
                        user_id=user_id,
                        source_id=source_id,
                        synced_at=now,
                    )
                    if not parsed:
                        continue
                    values, raw_json, srid, order_id, sticker_id = parsed
                    outcome = _upsert_goods_return_row(
                        conn,
                        repo,
                        user_id=user_id,
                        source_id=source_id,
                        values=values,
                        raw_json=raw_json,
                        srid=srid,
                        order_id=order_id,
                        sticker_id=sticker_id,
                    )
                    stats[outcome] += 1
            for key in ("fetched", "inserted", "updated", "unchanged", "skipped_foreign"):
                totals[key] += stats[key]
            window_stats.append(
                {
                    "date_from": win_from,
                    "date_to": win_to,
                    **stats,
                }
            )
        overall_from = windows[0][0] if windows else _parse_iso_date(date_from)
        overall_to = windows[-1][1] if windows else _parse_iso_date(date_to)
        totals["purged_foreign"] = _purge_foreign_goods_returns_in_range(
            repo,
            user_id=user_id,
            source_id=source_id,
            date_from=overall_from,
            date_to=overall_to,
            matchers=matchers,
            srid_to_order=srid_to_order,
            confirmed_order_ids=confirmed_order_ids,
            trust_report=trust_report,
            fetched_srids=fetched_srids if trust_report else None,
            fetched_stickers=fetched_stickers if trust_report else None,
            fetched_order_ids=fetched_order_ids if trust_report else None,
        )
    synced = totals["inserted"] + totals["updated"]
    warning = ""
    if range_clamped:
        warning = (
            f"Период синхронизации ограничен {GOODS_RETURN_DEFAULT_TOTAL_DAYS} днями "
            f"(WB хранит возвраты ~{GOODS_RETURN_DEFAULT_TOTAL_DAYS} дней)."
        )
    has_local_orders = bool(matchers.get("order_ids") or matchers.get("nm_ids"))
    if synced == 0 and totals["fetched"] > 0:
        extra = ""
        if totals["skipped_foreign"] > 0 and str(report_label or api_key_source or "").strip() == "settings":
            extra = (
                "Отчёт загружен глобальным ключом из Настроек, а не ключом источника. "
                "При нескольких кабинетах WB у каждого источника должен быть свой API-ключ."
            )
        elif not has_local_orders and not confirmed_order_ids and not trust_report:
            extra = (
                "Для этого источника нет заказов в базе FeedPilot — "
                "сначала синхронизируйте ВБ ФБС, затем повторите «Синхр. WB»"
            )
        elif totals["skipped_foreign"] > 0 and not trust_report:
            extra = (
                "Все строки отчёта WB не сопоставились с заказами этого источника. "
                "Проверьте, что выбран нужный источник и заказы синхронизированы "
                "(включая архив)."
            )
        elif totals["skipped_foreign"] > 0 and trust_report:
            extra = (
                f"Пропущено {totals['skipped_foreign']} строк без идентификатора "
                "(нет srid, stickerId, orderId, nmId)."
            )
        if extra:
            warning = f"{warning} {extra}".strip() if warning else extra
    return {
        "ok": True,
        "synced": synced,
        "inserted": totals["inserted"],
        "updated": totals["updated"],
        "unchanged": totals["unchanged"],
        "fetched": totals["fetched"],
        "skipped_foreign": totals["skipped_foreign"],
        "purged_foreign": totals["purged_foreign"],
        "warning": warning,
        "api_key_source": report_label or str(api_key_source or "").strip() or None,
        "report_trusted": trust_report,
        "range_clamped": range_clamped,
        "rate_limit_windows": totals.get("rate_limit_windows"),
        "windows": window_stats,
        "date_from": overall_from,
        "date_to": overall_to,
        "goods_cached_total": len(
            list_goods_returns(
                repo,
                user_id=user_id,
                source_id=source_id,
                date_from=overall_from,
                date_to=overall_to,
            )
        ),
    }


