_goods_return_sync_lock_guard = threading.Lock()
_goods_return_sync_locks: dict[str, threading.Lock] = {}

_goods_return_token_guard = threading.Lock()
_goods_return_token_locks: dict[str, threading.Lock] = {}
_goods_return_token_last_request: dict[str, float] = {}
_goods_return_token_block_guard = threading.Lock()
_goods_return_token_blocked_until: dict[str, float] = {}

_goods_return_job_guard = threading.Lock()
_goods_return_jobs: dict[str, dict[str, Any]] = {}


def _set_goods_return_token_block(
    *,
    api_key: str,
    retry_after: str = "",
    retry_seconds: int = 0,
) -> None:
    """Remember WB rate-limit until retry moment (per Analytics token)."""
    retry_at = _parse_wb_retry_at_msk(retry_after) if retry_after else None
    if retry_at is None and int(retry_seconds) > 0:
        retry_at = datetime.now(MSK) + timedelta(seconds=int(retry_seconds))
    if retry_at is None:
        return
    until = retry_at.timestamp()
    token_key = _analytics_token_key(api_key)
    with _goods_return_token_block_guard:
        prev = float(_goods_return_token_blocked_until.get(token_key, 0.0))
        _goods_return_token_blocked_until[token_key] = max(prev, until)


def _clear_goods_return_token_block(*, api_key: str) -> None:
    token_key = _analytics_token_key(api_key)
    with _goods_return_token_block_guard:
        _goods_return_token_blocked_until.pop(token_key, None)


def goods_return_rate_limit_status(*, api_key: str) -> dict[str, Any]:
    """Whether WB goods-return sync is blocked for this Analytics token."""
    token_key = _analytics_token_key(api_key)
    now = time.time()
    with _goods_return_token_block_guard:
        until = float(_goods_return_token_blocked_until.get(token_key, 0.0))
    if until <= now + 0.5:
        return {"blocked": False, "token_key": token_key}
    retry_at = datetime.fromtimestamp(until, tz=MSK)
    secs = max(0, int(until - now))
    clock = retry_at.strftime("%H:%M:%S МСК (%d.%m.%Y)")
    return {
        "blocked": True,
        "token_key": token_key,
        "retry_at": retry_at.isoformat(),
        "retry_at_msk": clock,
        "seconds_remaining": secs,
        "message": (
            "Синхронизация возвратов WB временно недоступна: WB ограничил частоту запросов. "
            f"Повторите после {clock}. "
            "Запрос к WB не отправлен — дождитесь этого времени."
        ),
    }


def ensure_goods_return_not_rate_limited(*, api_key: str) -> None:
    status = goods_return_rate_limit_status(api_key=api_key)
    if status.get("blocked"):
        raise GoodsReturnHttpError(
            str(status.get("message") or ""),
            code=429,
            retry_after=str(status.get("seconds_remaining") or 0),
            retry_seconds=int(status.get("seconds_remaining") or 0),
        )


def _goods_return_job_key(*, user_id: int, source_id: int) -> str:
    return f"wb-goods-return-job:{int(user_id)}:{int(source_id)}"


def get_goods_return_sync_job(
    *,
    user_id: int,
    source_id: int,
) -> dict[str, Any] | None:
    key = _goods_return_job_key(user_id=user_id, source_id=source_id)
    with _goods_return_job_guard:
        job = _goods_return_jobs.get(key)
        return dict(job) if isinstance(job, dict) else None


def start_goods_return_sync_async(
    *,
    user_id: int,
    source_id: int,
    sync_callable,
) -> dict[str, Any]:
    """Run ``sync_callable()`` in a daemon thread; return job handle for polling."""
    key = _goods_return_job_key(user_id=user_id, source_id=source_id)
    with _goods_return_job_guard:
        existing = _goods_return_jobs.get(key)
        if isinstance(existing, dict) and str(existing.get("status") or "") == "running":
            return {
                "ok": True,
                "async": True,
                "status": "running",
                "already_running": True,
                "source_id": int(source_id),
                "started_at": existing.get("started_at"),
                "message": (
                    "Синхронизация возвратов WB уже выполняется для этого источника. "
                    "Дождитесь завершения (~2 мин для 90 дней)."
                ),
            }
        started_at = datetime.now(UTC).isoformat()
        _goods_return_jobs[key] = {
            "status": "running",
            "source_id": int(source_id),
            "started_at": started_at,
        }

    def _worker() -> None:
        try:
            result = sync_callable()
            with _goods_return_job_guard:
                _goods_return_jobs[key] = {
                    "status": "ok",
                    "source_id": int(source_id),
                    "started_at": started_at,
                    "finished_at": datetime.now(UTC).isoformat(),
                    "result": result,
                }
        except GoodsReturnSyncInProgress as exc:
            with _goods_return_job_guard:
                _goods_return_jobs[key] = {
                    "status": "error",
                    "source_id": int(source_id),
                    "started_at": started_at,
                    "finished_at": datetime.now(UTC).isoformat(),
                    "error": str(exc),
                }
        except RuntimeError as exc:
            if _is_goods_return_rate_limit_error(exc):
                token_key = "unknown"
                retry_secs = _goods_return_rate_limit_retry_seconds(exc)
                _log.warning(
                    "goods-return async sync rate limited user=%s source=%s retry=%ss: %s",
                    user_id,
                    source_id,
                    retry_secs,
                    exc,
                )
            with _goods_return_job_guard:
                _goods_return_jobs[key] = {
                    "status": "error",
                    "source_id": int(source_id),
                    "started_at": started_at,
                    "finished_at": datetime.now(UTC).isoformat(),
                    "error": str(exc),
                }
        except Exception as exc:
            _log.exception("goods-return async sync failed user=%s source=%s", user_id, source_id)
            with _goods_return_job_guard:
                _goods_return_jobs[key] = {
                    "status": "error",
                    "source_id": int(source_id),
                    "started_at": started_at,
                    "finished_at": datetime.now(UTC).isoformat(),
                    "error": str(exc) or "Синхронизация не удалась",
                }

    threading.Thread(
        target=_worker,
        name=f"wb-goods-return-sync-{user_id}-{source_id}",
        daemon=True,
    ).start()
    return {
        "ok": True,
        "async": True,
        "status": "running",
        "already_running": False,
        "source_id": int(source_id),
        "started_at": started_at,
        "message": (
            "Синхронизация возвратов WB запущена в фоне (~2 мин для 90 дней). "
            "Не закрывайте окно — статус обновится автоматически."
        ),
    }


def _goods_return_sync_lock_key(*, user_id: int, cabinet_uid: int | None) -> str:
    uid = int(cabinet_uid or 0)
    return f"wb-goods-return:{int(user_id)}:{uid}"


def _analytics_token_key(api_key: str) -> str:
    """Stable key for WB Analytics token (uid preferred, hash fallback)."""
    key = str(api_key or "").strip()
    if not key:
        return "empty"
    uid = wb.wb_jwt_uid(key)
    if uid is not None:
        return f"uid:{uid}"
    return f"hash:{hashlib.sha256(key.encode('utf-8')).hexdigest()[:16]}"


@contextlib.contextmanager
def _goods_return_token_rate_slot(*, api_key: str, source_id: int | None = None):
    """Serialize goods-return API calls per Analytics token with 61s cooldown."""
    token_key = _analytics_token_key(api_key)
    with _goods_return_token_guard:
        lock = _goods_return_token_locks.setdefault(token_key, threading.Lock())
    lock.acquire()
    try:
        with _goods_return_token_guard:
            last = float(_goods_return_token_last_request.get(token_key, 0.0))
        wait = GOODS_RETURN_REQUEST_INTERVAL_SEC - (time.monotonic() - last)
        if wait > 0:
            _log.info(
                "goods-return token cooldown token=%s source_id=%s wait=%.1fs",
                token_key,
                source_id,
                wait,
            )
            time.sleep(wait)
        yield token_key
    finally:
        with _goods_return_token_guard:
            _goods_return_token_last_request[token_key] = time.monotonic()
        lock.release()


class GoodsReturnHttpError(RuntimeError):
    """WB goods-return HTTP error with optional rate-limit metadata."""

    def __init__(
        self,
        message: str,
        *,
        code: int = 0,
        retry_after: str = "",
        retry_seconds: int = 0,
    ) -> None:
        super().__init__(message)
        self.code = int(code)
        self.retry_after = str(retry_after or "")
        self.retry_seconds = max(0, int(retry_seconds))


def _parse_wb_retry_at_msk(retry_after: str) -> datetime | None:
    """Absolute retry moment from WB X-RateLimit-Retry (unix ts, ISO, or seconds)."""
    retry = str(retry_after or "").strip()
    if not retry:
        return None
    if retry.isdigit():
        val = int(retry)
        if val > 1_700_000_000:
            return datetime.fromtimestamp(val, tz=UTC).astimezone(MSK)
        if val > 0:
            return datetime.now(MSK) + timedelta(seconds=val)
        return None
    try:
        dt = datetime.fromisoformat(retry.replace("Z", "+00:00"))
        if dt.tzinfo is None:
            dt = dt.replace(tzinfo=UTC)
        return dt.astimezone(MSK)
    except Exception:
        return None


def _parse_wb_retry_seconds(retry_after: str) -> int:
    retry_at = _parse_wb_retry_at_msk(retry_after)
    if retry_at is None:
        return 0
    return max(0, int((retry_at - datetime.now(MSK)).total_seconds()))


def _is_goods_return_rate_limit_error(exc: BaseException) -> bool:
    if isinstance(exc, GoodsReturnHttpError):
        return exc.code == 429
    return (
        "Лимит WB на отчёт по возвратам" in str(exc)
        or "WB ограничил частоту запросов" in str(exc)
    )


def _goods_return_rate_limit_retry_seconds(exc: BaseException) -> int:
    if isinstance(exc, GoodsReturnHttpError) and exc.retry_seconds > 0:
        return exc.retry_seconds
    text = str(exc)
    match = re.search(r"через\s+(\d+)\s+мин", text)
    if match:
        return int(match.group(1)) * 60
    match = re.search(r"через\s+(\d+)\s+сек", text)
    if match:
        return int(match.group(1))
    match = re.search(r"через\s+(\d+)\s+ч", text)
    if match:
        return int(match.group(1)) * 3600
    return GOODS_RETURN_REQUEST_INTERVAL_SEC


class GoodsReturnSyncInProgress(RuntimeError):
    """Another goods-return sync is running for this WB seller cabinet."""


@contextlib.contextmanager
def goods_return_sync_lock(*, user_id: int, cabinet_uid: int | None):
    key = _goods_return_sync_lock_key(user_id=user_id, cabinet_uid=cabinet_uid)
    with _goods_return_sync_lock_guard:
        lock = _goods_return_sync_locks.setdefault(key, threading.Lock())
    if not lock.acquire(blocking=False):
        raise GoodsReturnSyncInProgress(
            "Синхронизация возвратов WB для этого кабинета уже выполняется. "
            "Дождитесь завершения или повторите через 1–2 мин."
        )
    try:
        yield
    finally:
        lock.release()


def resolve_goods_return_api_key(
    *,
    source_api_key: str | None,
    source_analytics_api_key: str | None = None,
    fallback_analytics_key: str | None,
) -> tuple[str, str, bool]:
    """Pick WB token for goods-return report.

    goods-return lives on seller-analytics API and requires Analytics/Statistics
    scope. Marketplace-only source tokens get 403. When the global Settings key
    belongs to the same seller (JWT uid), it is used as fallback.

    Returns ``(api_key, api_key_source, trust_report)``.
    """
    ordered, trust = resolve_goods_return_api_keys(
        source_api_key=source_api_key,
        source_analytics_api_key=source_analytics_api_key,
        fallback_analytics_key=fallback_analytics_key,
    )
    key, label = ordered[0]
    return key, label, trust


def resolve_goods_return_api_keys(
    *,
    source_api_key: str | None,
    source_analytics_api_key: str | None = None,
    fallback_analytics_key: str | None,
) -> tuple[list[tuple[str, str]], bool]:
    """Ordered Analytics-capable keys: [(token, label), ...], trust_report."""
    source = str(source_api_key or "").strip()
    source_analytics = str(source_analytics_api_key or "").strip()
    fallback = str(fallback_analytics_key or "").strip()
    source_uid = wb.wb_jwt_uid(source) if source else None

    ordered: list[tuple[str, str]] = []
    seen: set[str] = set()

    def _add(key: str, label: str) -> None:
        if not key or key in seen:
            return
        if not wb.wb_token_has_goods_return_scope(key):
            return
        seen.add(key)
        ordered.append((key, label))

    if source_analytics:
        _add(source_analytics, "source_analytics")
    if source:
        _add(source, "source")
    if fallback:
        fb_uid = wb.wb_jwt_uid(fallback)
        if source_uid is None or fb_uid == source_uid:
            _add(fallback, "settings")

    if not ordered:
        raise RuntimeError(
            _goods_return_key_resolution_error(
                source, fallback, source_uid, has_source_analytics=bool(source_analytics)
            )
        )

    key, _label = ordered[0]
    trust = bool(source_uid and wb.wb_jwt_uid(key) == source_uid)
    return ordered, trust


def _goods_return_key_resolution_error(
    source_key: str,
    fallback_key: str,
    source_uid: int | None,
    *,
    has_source_analytics: bool = False,
) -> str:
    if (
        fallback_key
        and wb.wb_token_has_goods_return_scope(fallback_key)
        and source_uid
        and wb.wb_jwt_uid(fallback_key) not in (None, source_uid)
    ):
        return (
            "Analytics-ключ в Настройках (Честный знак) принадлежит другому кабинету WB. "
            "Обновите API-токен источника с категориями «Маркетплейс» и «Аналитика» "
            "или укажите Analytics-ключ того же кабинета в Настройках → ЧЗ."
        )
    if has_source_analytics:
        return (
            "API-токен источника не имеет категории «Аналитика» или «Статистика». "
            "Создайте в ЛК WB токен с категориями «Маркетплейс» и «Аналитика» "
            "и обновите ключ источника."
        )
    if source_key and not wb.wb_token_has_goods_return_scope(source_key):
        scopes = ", ".join(wb.wb_token_scope_labels(source_key)) or "не определены"
        return (
            "API-ключ источника не имеет категории «Аналитика» или «Статистика» "
            f"(сейчас: {scopes}). Создайте в ЛК WB новый токен с категорией «Аналитика» "
            "и обновите ключ источника."
        )
    return (
        "Не задан подходящий WB API-ключ для отчёта по возвратам "
        "(нужна категория «Аналитика» или «Статистика»)."
    )


