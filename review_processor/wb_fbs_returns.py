def export_return_scans_csv(items: list[dict[str, Any]]) -> str:
    buf = io.StringIO()
    writer = csv.writer(buf, delimiter=";")
    writer.writerow(
        [
            "Дата",
            "Тип",
            "Заказ",
            "Стикер возврата",
            "Стикер заказа",
            "КИЗ",
            "Товар",
            "Артикул",
            "ШК",
        ]
    )
    for item in items:
        writer.writerow(
            [
                str(item.get("scanned_at") or ""),
                str(item.get("scan_type") or ""),
                str(item.get("order_id") or ""),
                str(item.get("return_sticker_id") or ""),
                str(item.get("assembly_sticker_number") or item.get("assembly_sticker_barcode") or ""),
                str(item.get("kiz_code") or ""),
                str(item.get("product_name") or ""),
                str(item.get("product_article") or ""),
                ", ".join(str(x) for x in (item.get("product_barcodes") or [])),
            ]
        )
    return "\ufeff" + buf.getvalue()


def default_sync_date_range(days: int = 31) -> tuple[str, str]:
    end = date.today()
    start = end - timedelta(days=max(1, days) - 1)
    return start.isoformat(), end.isoformat()


