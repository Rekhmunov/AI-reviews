def _digits_only(value: object) -> str:
    return re.sub(r"\D+", "", str(value or ""))


def _scan_key(value: object) -> str:
    return kiz_restore.normalize_sticker_scan(value).casefold()


def _parse_iso_date(value: object) -> str:
    text = str(value or "").strip()
    if not text:
        return ""
    return text[:10] if len(text) >= 10 else text


def fetch_goods_return_report(
    *,
    api_key: str,
    date_from: str,
    date_to: str,
    timeout: int = 60,
) -> list[dict[str, Any]]:
    """WB Analytics: GET /api/v1/analytics/goods-return (max 31 days)."""
    params = urlencode(
        {"dateFrom": _parse_iso_date(date_from), "dateTo": _parse_iso_date(date_to)}
    )
    url = f"{WB_ANALYTICS_API}/api/v1/analytics/goods-return?{params}"
    req = urllib.request.Request(
        url,
        method="GET",
        headers={
            "Authorization": str(api_key or "").strip(),
            "Accept": "application/json",
            "User-Agent": "FeedPilot-WBFBS-Returns/1.0",
        },
    )
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            payload = resp.read()
    except urllib.error.HTTPError as exc:
        err = ""
        try:
            err = exc.read().decode("utf-8", errors="replace")[:500]
        except Exception:
            pass
        raise RuntimeError(f"WB goods-return HTTP {exc.code}: {err or exc.reason}") from exc
    if not payload:
        return []
    parsed = json.loads(payload.decode("utf-8"))
    if isinstance(parsed, dict):
        report = parsed.get("report")
        if isinstance(report, list):
            return [x for x in report if isinstance(x, dict)]
    if isinstance(parsed, list):
        return [x for x in parsed if isinstance(x, dict)]
    return []


def sync_goods_returns(
    repo: ReviewRepository,
    *,
    user_id: int,
    source_id: int,
    api_key: str,
    date_from: str,
    date_to: str,
) -> dict[str, Any]:
    ensure_wb_fbs_returns_tables(repo)
    rows = fetch_goods_return_report(
        api_key=api_key, date_from=date_from, date_to=date_to
    )
    now = datetime.now(UTC).isoformat()
    upserted = 0
    with repo._connect() as conn:
        for row in rows:
            try:
                order_id = int(row.get("orderId") or 0)
            except (TypeError, ValueError):
                order_id = 0
            sticker_id = str(row.get("stickerId") or "").strip()
            srid = str(row.get("srid") or "").strip()
            if not srid and not sticker_id and order_id <= 0:
                continue
            barcode = str(row.get("barcode") or "").strip()
            shk_id = str(row.get("shkId") or "").strip()
            try:
                nm_id = int(row.get("nmId") or 0) or None
            except (TypeError, ValueError):
                nm_id = None
            raw_json = json.dumps(row, ensure_ascii=False)
            status = str(row.get("status") or "").strip()
            reason = str(row.get("reason") or "").strip()
            ready_dt = str(row.get("readyToReturnDt") or "").strip()
            completed_dt = str(row.get("completedDt") or "").strip()
            order_dt = str(row.get("orderDt") or "").strip()
            values = (
                user_id,
                source_id,
                order_id,
                sticker_id,
                barcode,
                shk_id,
                nm_id,
                srid,
                status,
                reason,
                ready_dt,
                completed_dt,
                order_dt,
                raw_json,
                now,
            )
            if srid:
                conn.execute(
                    repo._sql(
                        """
                        INSERT INTO wb_fbs_goods_returns (
                            user_id, source_id, wb_order_id, sticker_id, barcode, shk_id,
                            nm_id, srid, status, reason, ready_to_return_dt, completed_dt,
                            order_dt, raw_json, synced_at
                        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                        ON CONFLICT (user_id, source_id, srid) WHERE srid <> ''
                        DO UPDATE SET
                            wb_order_id = EXCLUDED.wb_order_id,
                            sticker_id = EXCLUDED.sticker_id,
                            barcode = EXCLUDED.barcode,
                            shk_id = EXCLUDED.shk_id,
                            nm_id = EXCLUDED.nm_id,
                            status = EXCLUDED.status,
                            reason = EXCLUDED.reason,
                            ready_to_return_dt = EXCLUDED.ready_to_return_dt,
                            completed_dt = EXCLUDED.completed_dt,
                            order_dt = EXCLUDED.order_dt,
                            raw_json = EXCLUDED.raw_json,
                            synced_at = EXCLUDED.synced_at
                        """
                    ),
                    values,
                )
            elif order_id > 0 and sticker_id:
                cur = conn.execute(
                    repo._sql(
                        """
                        UPDATE wb_fbs_goods_returns SET
                            barcode = ?, shk_id = ?, nm_id = ?, status = ?, reason = ?,
                            ready_to_return_dt = ?, completed_dt = ?, order_dt = ?,
                            raw_json = ?, synced_at = ?
                        WHERE user_id = ? AND source_id = ? AND wb_order_id = ?
                          AND sticker_id = ? AND srid = ''
                        """
                    ),
                    (
                        barcode,
                        shk_id,
                        nm_id,
                        status,
                        reason,
                        ready_dt,
                        completed_dt,
                        order_dt,
                        raw_json,
                        now,
                        user_id,
                        source_id,
                        order_id,
                        sticker_id,
                    ),
                )
                if getattr(cur, "rowcount", 0) == 0:
                    conn.execute(
                        repo._sql(
                            """
                            INSERT INTO wb_fbs_goods_returns (
                                user_id, source_id, wb_order_id, sticker_id, barcode, shk_id,
                                nm_id, srid, status, reason, ready_to_return_dt, completed_dt,
                                order_dt, raw_json, synced_at
                            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                            """
                        ),
                        values,
                    )
            else:
                conn.execute(
                    repo._sql(
                        """
                        INSERT INTO wb_fbs_goods_returns (
                            user_id, source_id, wb_order_id, sticker_id, barcode, shk_id,
                            nm_id, srid, status, reason, ready_to_return_dt, completed_dt,
                            order_dt, raw_json, synced_at
                        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                        """
                    ),
                    values,
                )
            upserted += 1
    return {"ok": True, "synced": upserted, "date_from": date_from, "date_to": date_to}


def _goods_return_rows(repo: ReviewRepository, *, user_id: int, source_id: int) -> list[dict[str, Any]]:
    ensure_wb_fbs_returns_tables(repo)
    with repo._connect() as conn:
        rows = conn.execute(
            repo._sql(
                """
                SELECT * FROM wb_fbs_goods_returns
                WHERE user_id = ? AND source_id = ?
                ORDER BY synced_at DESC
                """
            ),
            (user_id, source_id),
        ).fetchall()
    return [repo._row_to_dict(r) for r in rows]


def find_goods_return_by_scan(
    repo: ReviewRepository,
    *,
    user_id: int,
    source_id: int,
    scan: str,
) -> dict[str, Any] | None:
    raw = kiz_restore.normalize_sticker_scan(scan)
    if not raw:
        return None
    raw_key = _scan_key(raw)
    digits = _digits_only(raw)
    for row in _goods_return_rows(repo, user_id=user_id, source_id=source_id):
        sticker_id = str(row.get("sticker_id") or "").strip()
        if sticker_id and (
            sticker_id == raw
            or sticker_id == digits
            or _scan_key(sticker_id) == raw_key
        ):
            return row
        barcode = str(row.get("barcode") or "").strip()
        shk_id = str(row.get("shk_id") or "").strip()
        if barcode and (barcode == raw or _digits_only(barcode) == digits):
            return row
        if shk_id and (shk_id == raw or _digits_only(shk_id) == digits):
            return row
    return None


def _catalog_barcodes_index(repo: ReviewRepository, *, user_id: int) -> dict[str, dict[str, Any]]:
    index: dict[str, dict[str, Any]] = {}
    for p in repo.list_product_photos(user_id=user_id):
        for b in p.get("barcodes") or []:
            code = str(b or "").strip()
            if not code:
                continue
            index[code] = p
            index[code.casefold()] = p
            d = _digits_only(code)
            if d:
                index[d] = p
    return index


def _product_from_order(
    repo: ReviewRepository,
    *,
    user_id: int,
    order_row: dict[str, Any] | None,
) -> dict[str, Any]:
    if not order_row:
        return {}
    article = str(order_row.get("article") or "").strip()
    nm_id = str(order_row.get("nm_id") or "").strip()
    name_map = repo.get_product_name_by_article(user_id=user_id)
    photo_map = repo.get_product_photo_map(user_id=user_id)
    name = (
        name_map.get(article)
        or name_map.get(article.casefold())
        or name_map.get(nm_id)
        or name_map.get(nm_id.casefold())
        or ""
    )
    photo = photo_map.get(article) or photo_map.get(nm_id) or ""
    barcodes: list[str] = []
    try:
        parsed = json.loads(order_row.get("skus_json") or "[]")
        if isinstance(parsed, list):
            barcodes = [str(x).strip() for x in parsed if str(x or "").strip()]
    except Exception:
        pass
    catalog = _catalog_barcodes_index(repo, user_id=user_id)
    for p in repo.list_product_photos(user_id=user_id):
        if article and str(p.get("supplier_article") or "").strip() == article:
            for b in p.get("barcodes") or []:
                text = str(b or "").strip()
                if text and text not in barcodes:
                    barcodes.append(text)
            break
        if nm_id and str(p.get("wb_nmid") or "").strip() == nm_id:
            for b in p.get("barcodes") or []:
                text = str(b or "").strip()
                if text and text not in barcodes:
                    barcodes.append(text)
            break
    return {
        "product_name": name,
        "product_article": article,
        "product_photo": photo,
        "product_barcodes": barcodes,
    }


def _product_from_gtin(
    repo: ReviewRepository,
    *,
    user_id: int,
    gtin14: str,
) -> dict[str, Any]:
    if not gtin14:
        return {}
    catalog = _catalog_barcodes_index(repo, user_id=user_id)
    p = catalog.get(gtin14) or catalog.get(gtin14.lstrip("0")) or catalog.get(_digits_only(gtin14))
    if not p:
        return {}
    pid = int(p.get("id") or 0)
    photo = f"/api/products/photo/{pid}" if pid and p.get("photo_path") else ""
    return {
        "product_name": str(p.get("name") or "").strip(),
        "product_article": str(p.get("supplier_article") or "").strip(),
        "product_photo": photo,
        "product_barcodes": list(p.get("barcodes") or []),
    }


