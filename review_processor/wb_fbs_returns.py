def _parse_iso_date(value: object) -> str:
    text = str(value or "").strip()
    if not text:
        return ""
    return text[:10] if len(text) >= 10 else text


def _parse_sync_date(value: str) -> date:
    return date.fromisoformat(_parse_iso_date(value))


def iter_goods_return_windows(
    date_from: str,
    date_to: str,
    *,
    chunk_days: int = GOODS_RETURN_CHUNK_DAYS,
) -> list[tuple[str, str]]:
    """Split a range into non-overlapping WB windows (each ≤ 31 days)."""
    start = _parse_sync_date(date_from)
    end = _parse_sync_date(date_to)
    if end < start:
        start, end = end, start
    max_chunk = min(max(1, int(chunk_days)), GOODS_RETURN_MAX_WINDOW_DAYS)
    windows: list[tuple[str, str]] = []
    cur = end
    while cur >= start:
        win_start = max(start, cur - timedelta(days=max_chunk - 1))
        windows.append((win_start.isoformat(), cur.isoformat()))
        cur = win_start - timedelta(days=1)
    windows.reverse()
    return windows


def _http_header_get(headers: Any, *names: str) -> str:
    if headers is None:
        return ""
    for name in names:
        try:
            val = headers.get(name)
        except Exception:
            val = None
        if val is None and hasattr(headers, "get"):
            try:
                val = headers.get(name.lower())
            except Exception:
                val = None
        if val is not None and str(val).strip():
            return str(val).strip()
    return ""


def _format_wb_retry_hint(retry_after: str) -> str:
    retry = str(retry_after or "").strip()
    if not retry:
        return ""
    if retry.isdigit():
        secs = int(retry)
        if secs > 1_700_000_000:
            dt = datetime.fromtimestamp(secs, tz=UTC).astimezone(MSK)
            return f" Повторите после {dt.strftime('%H:%M')} МСК ({dt.strftime('%d.%m.%Y')})."
        if secs >= 3600:
            hours = secs // 3600
            mins = (secs % 3600 + 59) // 60
            if mins and hours < 24:
                return f" Повторите примерно через {hours} ч {mins} мин."
            return f" Повторите примерно через {hours} ч."
        if secs >= 60:
            return f" Повторите примерно через {(secs + 59) // 60} мин."
        if secs > 0:
            return f" Повторите примерно через {secs} сек."
        return ""
    try:
        dt = datetime.fromisoformat(retry.replace("Z", "+00:00"))
        if dt.tzinfo is None:
            dt = dt.replace(tzinfo=UTC)
        msk = dt.astimezone(MSK)
        return f" Повторите после {msk.strftime('%H:%M')} МСК ({msk.strftime('%d.%m.%Y')})."
    except Exception:
        return f" Повторите после: {retry}."


def _format_goods_return_429_message(retry_after: str) -> str:
    """User-facing 429 message with exact retry time from WB X-RateLimit-Retry."""
    retry_at = _parse_wb_retry_at_msk(retry_after)
    if retry_at is not None:
        clock = retry_at.strftime("%H:%M:%S МСК (%d.%m.%Y)")
        return (
            "Синхронизация возвратов WB не выполнена: WB ограничил частоту запросов. "
            f"Повторите после {clock}. "
            "Вернитесь к «Синхр. WB» после этого времени."
        )
    return (
        "Синхронизация возвратов WB не выполнена: WB ограничил частоту запросов. "
        "Подождите ~1 мин и нажмите «Синхр. WB» снова."
    )


def format_wb_goods_return_http_error(
    *,
    code: int,
    body: str = "",
    retry_after: str = "",
    reason: str = "",
) -> GoodsReturnHttpError:
    """Human-readable WB Analytics goods-return errors (esp. 429 rate limit)."""
    if int(code) == 429:
        retry_secs = _parse_wb_retry_seconds(retry_after)
        msg = _format_goods_return_429_message(retry_after)
        return GoodsReturnHttpError(
            msg,
            code=429,
            retry_after=retry_after,
            retry_seconds=retry_secs,
        )
    if int(code) == 403 and (
        "scope is not allowed" in (body or "").lower()
        or "scope is not allowed" in (reason or "").lower()
    ):
        return GoodsReturnHttpError(
            "WB goods-return: у API-ключа нет категории «Аналитика» или «Статистика». "
            "Создайте токен в ЛК WB с категорией «Аналитика» и обновите ключ источника.",
            code=403,
        )
    detail = (body or reason or "").strip()
    if detail:
        return GoodsReturnHttpError(f"WB goods-return HTTP {code}: {detail[:500]}", code=int(code))
    return GoodsReturnHttpError(f"WB goods-return HTTP {code}", code=int(code))


