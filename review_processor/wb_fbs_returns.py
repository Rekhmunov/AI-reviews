def _return_scans_search_sql(search: str) -> tuple[str, list[Any]]:
    q = str(search or "").strip()
    if not q:
        return "", []
    pattern = f"%{q}%"
    clause = """(
        CAST(order_id AS TEXT) ILIKE ?
        OR return_sticker_id ILIKE ?
        OR assembly_sticker_barcode ILIKE ?
        OR assembly_sticker_number ILIKE ?
        OR kiz_code ILIKE ?
        OR scan_raw ILIKE ?
        OR product_name ILIKE ?
        OR product_article ILIKE ?
        OR product_barcodes_json ILIKE ?
        OR matched_order_ids_json ILIKE ?
    )"""
    return clause, [pattern] * 10


def _scan_row_to_api(row: dict[str, Any]) -> dict[str, Any]:
    if not row:
        return {}
    out = dict(row)
    try:
        out["matched_order_ids"] = json.loads(out.pop("matched_order_ids_json", "[]") or "[]")
    except Exception:
        out["matched_order_ids"] = []
    try:
        out["product_barcodes"] = json.loads(out.pop("product_barcodes_json", "[]") or "[]")
    except Exception:
        out["product_barcodes"] = []
    out.pop("product_barcodes_json", None)
    out.pop("matched_order_ids_json", None)
    return out


