def upsert_return_rows(
    repo: ReviewRepository,
    *,
    user_id: int,
    source_id: int,
    items: list[dict[str, Any]],
) -> int:
    """Persist API rows. Returns number of upserted rows."""
    ensure_pvz_return_tables(repo)
    saved = 0
    with repo._connect() as conn:
        for item in items:
            fields = _extract_return_fields(item)
            if not fields:
                continue
            # Keep only ReceivedBySeller in the PVZ cache.
            status = str(fields.get("visual_status") or "").strip().casefold()
            if status and status != ISSUED_STATUS:
                continue
            if not fields.get("completed_dt"):
                continue
            conn.execute(
                repo._sql(
                    """
                    INSERT INTO ozon_fbs_pvz_returns (
                        user_id, source_id, return_id, posting_number, order_id,
                        order_number, visual_status, completed_dt, offer_id, sku,
                        product_name, quantity, barcode, raw_json, updated_at
                    ) VALUES (
                        ?, ?, ?, ?, ?,
                        ?, ?, ?, ?, ?,
                        ?, ?, ?, ?, NOW()
                    )
                    ON CONFLICT (user_id, source_id, return_id) DO UPDATE SET
                        posting_number = EXCLUDED.posting_number,
                        order_id = EXCLUDED.order_id,
                        order_number = EXCLUDED.order_number,
                        visual_status = EXCLUDED.visual_status,
                        completed_dt = EXCLUDED.completed_dt,
                        offer_id = EXCLUDED.offer_id,
                        sku = EXCLUDED.sku,
                        product_name = EXCLUDED.product_name,
                        quantity = EXCLUDED.quantity,
                        barcode = EXCLUDED.barcode,
                        raw_json = EXCLUDED.raw_json,
                        updated_at = NOW()
                    """
                ),
                (
                    int(user_id),
                    int(source_id),
                    int(fields["return_id"]),
                    fields["posting_number"],
                    fields["order_id"],
                    fields["order_number"],
                    fields["visual_status"] or "ReceivedBySeller",
                    fields["completed_dt"],
                    fields["offer_id"],
                    fields["sku"],
                    fields["product_name"],
                    int(fields["quantity"]),
                    fields["barcode"],
                    fields["raw_json"],
                ),
            )
            saved += 1
    return saved


def sync_source_returns(
    repo: ReviewRepository,
    *,
    user_id: int,
    source_id: int,
    client_id: str,
    api_key: str,
    date_from: str,
    date_to: str,
) -> int:
    """Pull ReceivedBySeller returns for one cabinet into the local cache."""
    start = date.fromisoformat(str(date_from)[:10])
    end = date.fromisoformat(str(date_to)[:10])
    time_from, time_to = _msk_day_bounds_utc(start, end)
    client = ozon.OzonFbsClient(client_id=client_id, api_key=api_key)
    last_id = 0
    total = 0
    pages = 0
    while True:
        pages += 1
        if pages > 200:
            raise RuntimeError("Слишком много страниц возвратов Ozon")
        data = fetch_returns_page(
            client,
            time_from=time_from,
            time_to=time_to,
            last_id=last_id,
        )
        rows = data.get("returns")
        if not isinstance(rows, list):
            rows = []
        total += upsert_return_rows(
            repo, user_id=user_id, source_id=source_id, items=rows
        )
        has_next = bool(data.get("has_next"))
        try:
            next_id = int(data.get("last_id") or 0)
        except (TypeError, ValueError):
            next_id = 0
        if not has_next or next_id <= 0 or next_id == last_id or not rows:
            break
        last_id = next_id
        time.sleep(0.05)
    return total


def get_pvz_sync_job(*, user_id: int) -> dict[str, Any] | None:
    with _pvz_job_guard:
        job = _pvz_jobs.get(int(user_id))
        if not isinstance(job, dict):
            return None
        out = dict(job)
    errors = out.get("errors")
    if isinstance(errors, list):
        out["errors"] = list(errors)
    return out


def _set_pvz_job(user_id: int, **fields: Any) -> None:
    with _pvz_job_guard:
        job = _pvz_jobs.get(int(user_id))
        if not isinstance(job, dict):
            return
        job.update(fields)


def start_pvz_sync(
    repo: ReviewRepository,
    *,
    user_id: int,
    date_from: str = "",
    date_to: str = "",
) -> dict[str, Any]:
    """Pull returns for each saved source, sequentially, then list locally.

    Calendar ``date_from``/``date_to`` are ignored: sync always uses the last
    31 days ending today (Moscow). Those bounds are returned so the UI can
    show the synced period in the table.
    """
    del date_from, date_to
    start, end = sync_display_range()
    view = settings_view(repo, user_id=user_id)
    sources = [s for s in (view.get("sources") or []) if s.get("selected")]
    if not sources:
        raise ValueError(EMPTY_SOURCES_MESSAGE)
    oz_from, oz_to = ozon_query_window(end)
    with _pvz_job_guard:
        existing = _pvz_jobs.get(int(user_id))
        if isinstance(existing, dict) and str(existing.get("status") or "") == "running":
            return {
                "ok": True,
                "async": True,
                "status": "running",
                "already_running": True,
                "message": str(existing.get("message") or "Синхронизация уже выполняется"),
                "date_from": start.isoformat(),
                "date_to": end.isoformat(),
            }
        started_at = datetime.now(UTC).isoformat()
        _pvz_jobs[int(user_id)] = {
            "status": "running",
            "message": "Запуск…",
            "started_at": started_at,
            "finished_at": "",
            "errors": [],
            "date_from": start.isoformat(),
            "date_to": end.isoformat(),
            "ozon_date_from": oz_from,
            "ozon_date_to": oz_to,
            "sources_done": 0,
            "sources_total": len(sources),
        }

    source_snapshot = [{"id": int(s["id"]), "name": str(s.get("name") or "")} for s in sources]

    def _worker() -> None:
        errors: list[str] = []
        done = 0
        try:
            for index, source in enumerate(source_snapshot, start=1):
                source_id = int(source["id"])
                name = str(source.get("name") or f"Источник {source_id}")
                prefix = f"{index}/{len(source_snapshot)} {name}"
                src_full = repo.get_supply_source_with_key(user_id=user_id, source_id=source_id)
                if not src_full or not ozon.is_ozon_fbs_source(src_full):
                    errors.append(f"{name}: источник не найден")
                    _set_pvz_job(user_id, message=errors[-1], errors=list(errors))
                    continue
                client_id = str(src_full.get("client_id") or "").strip()
                api_key = str(src_full.get("api_key") or "").strip()
                if not client_id or not api_key:
                    errors.append(f"{name}: не задан Client-Id или Api-Key")
                    _set_pvz_job(user_id, message=f"{prefix}: нет ключей", errors=list(errors))
                    continue
                _set_pvz_job(user_id, message=f"{prefix}: загрузка возвратов Ozon…")
                try:
                    sync_source_returns(
                        repo,
                        user_id=user_id,
                        source_id=source_id,
                        client_id=client_id,
                        api_key=api_key,
                        date_from=oz_from,
                        date_to=oz_to,
                    )
                except Exception as exc:
                    _log.warning("ozon pvz returns sync source %s failed: %s", source_id, exc)
                    errors.append(f"{name}: {exc}")
                    _set_pvz_job(user_id, message=f"{prefix}: {exc}", errors=list(errors))
                    continue
                done += 1
                _set_pvz_job(
                    user_id,
                    message=f"{prefix}: готово",
                    sources_done=done,
                    errors=list(errors),
                )
            message = "Готово" if not errors else "Готово с ошибками"
            _set_pvz_job(
                user_id,
                status="ok" if done or not errors else "error",
                message=message,
                errors=list(errors),
                sources_done=done,
                finished_at=datetime.now(UTC).isoformat(),
            )
        except Exception as exc:
            _log.exception("ozon pvz returns sync failed user=%s", user_id)
            _set_pvz_job(
                user_id,
                status="error",
                message=str(exc) or "Синхронизация не удалась",
                errors=list(errors),
                sources_done=done,
                finished_at=datetime.now(UTC).isoformat(),
            )

    threading.Thread(
        target=_worker,
        name=f"ozon-pvz-returns-{int(user_id)}",
        daemon=True,
    ).start()
    return {
        "ok": True,
        "async": True,
        "status": "running",
        "already_running": False,
        "message": "Запуск…",
        "date_from": start.isoformat(),
        "date_to": end.isoformat(),
        "ozon_date_from": oz_from,
        "ozon_date_to": oz_to,
    }
