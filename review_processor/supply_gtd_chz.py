def ensure_supply_gtd_chz_tables(repo: ReviewRepository) -> None:
    gtd_mod.ensure_supply_gtd_tables(repo)
    with repo._connect() as conn:
        conn.execute(
            repo._sql(
                """
                CREATE TABLE IF NOT EXISTS supply_gtd_chz_kiz_state (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL,
                    gtd_id BIGINT NOT NULL REFERENCES supply_gtd_documents(id)
                        ON DELETE CASCADE,
                    kiz_short TEXT NOT NULL,
                    cis_status TEXT NOT NULL DEFAULT '',
                    cis_status_kind TEXT NOT NULL DEFAULT '',
                    cis_status_label TEXT NOT NULL DEFAULT '',
                    cis_owner_inn TEXT NOT NULL DEFAULT '',
                    cis_status_error TEXT NOT NULL DEFAULT '',
                    cis_checked_at TIMESTAMPTZ,
                    last_op TEXT NOT NULL DEFAULT '',
                    last_doc_id TEXT NOT NULL DEFAULT '',
                    last_doc_type TEXT NOT NULL DEFAULT '',
                    last_op_status TEXT NOT NULL DEFAULT '',
                    last_op_error TEXT NOT NULL DEFAULT '',
                    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                    UNIQUE (user_id, gtd_id, kiz_short)
                )
                """
            )
        )
        conn.execute(
            repo._sql(
                """
                CREATE INDEX IF NOT EXISTS idx_supply_gtd_chz_state_gtd
                ON supply_gtd_chz_kiz_state (user_id, gtd_id)
                """
            )
        )
        conn.execute(
            repo._sql(
                """
                CREATE TABLE IF NOT EXISTS supply_gtd_chz_runs (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL,
                    gtd_id BIGINT NOT NULL REFERENCES supply_gtd_documents(id)
                        ON DELETE CASCADE,
                    op TEXT NOT NULL,
                    status TEXT NOT NULL DEFAULT 'running',
                    requested INTEGER NOT NULL DEFAULT 0,
                    ok_count INTEGER NOT NULL DEFAULT 0,
                    err_count INTEGER NOT NULL DEFAULT 0,
                    log_text TEXT NOT NULL DEFAULT '',
                    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                    finished_at TIMESTAMPTZ
                )
                """
            )
        )
        conn.execute(
            repo._sql(
                """
                CREATE INDEX IF NOT EXISTS idx_supply_gtd_chz_runs_gtd
                ON supply_gtd_chz_runs (user_id, gtd_id, id DESC)
                """
            )
        )


def _moscow_today() -> str:
    try:
        return datetime.now(ZoneInfo("Europe/Moscow")).strftime("%Y-%m-%d")
    except Exception:
        return datetime.now(timezone.utc).strftime("%Y-%m-%d")


def _b64_json(obj: dict[str, Any]) -> str:
    raw = json.dumps(obj, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    return base64.b64encode(raw).decode("ascii")


def _append_log(lines: list[str], msg: str) -> None:
    ts = datetime.now(timezone.utc).strftime("%H:%M:%S")
    lines.append(f"[{ts}] {msg}")


def _require_gtd(
    repo: ReviewRepository, *, user_id: int, gtd_id: int
) -> dict[str, Any]:
    item = gtd_mod.get_gtd_by_id(repo, user_id=user_id, gtd_id=int(gtd_id))
    if not item:
        raise ValueError("ГТД не найдена")
    return item


def _chz_settings_ready(repo: ReviewRepository, *, user_id: int) -> dict[str, Any]:
    settings = kiz_circ.get_chz_settings(repo, user_id=user_id)
    if not settings.get("is_enabled"):
        raise ValueError("ЧЗ выключен в Настройки → ЧЗ")
    inn = str(settings.get("participant_inn") or "").strip()
    if not inn:
        raise ValueError("Укажите ИНН участника в Настройки → ЧЗ")
    pg = str(settings.get("product_group") or "").strip()
    if not pg:
        raise ValueError("Укажите товарную группу в Настройки → ЧЗ")
    if pg.isdigit():
        raise ValueError(
            "Товарная группа — код True API (например lp, shoes), не число"
        )
    return settings


def _display_kind(
    *,
    status: str,
    owner_inn: str,
    participant_inn: str,
    error: str = "",
) -> tuple[str, str]:
    """Return (label, kind). Foreign owner → transferred (not withdrawn)."""
    if error and not status:
        return (error[:80] or "Ошибка", KIND_ERROR)
    if not status and not owner_inn:
        return ("Не проверен", KIND_EMPTY)
    if kiz_circ.cis_owner_is_foreign(
        owner_inn=owner_inn, participant_inn=participant_inn
    ):
        return ("Передан", KIND_TRANSFERRED)
    label = kiz_circ.cis_status_label(status)
    kind = kiz_circ.classify_cis_status(status)
    if kind == "unknown" and not status:
        return ("Не проверен", KIND_EMPTY)
    if kind == "unknown":
        kind = KIND_OTHER
    return (label or status or "—", kind)


def list_gtd_kiz_for_chz(
    repo: ReviewRepository,
    *,
    user_id: int,
    gtd_id: int,
    offset: int = 0,
    limit: int = 2000,
    status_kind: str = "",
) -> dict[str, Any]:
    ensure_supply_gtd_chz_tables(repo)
    gtd = _require_gtd(repo, user_id=user_id, gtd_id=gtd_id)
    off = max(0, int(offset or 0))
    lim = max(1, min(int(limit or 2000), 5000))
    kind_filter = str(status_kind or "").strip()

    with repo._connect() as conn:
        total_row = conn.execute(
            repo._sql(
                """
                SELECT COUNT(*) AS n FROM supply_gtd_kiz
                WHERE user_id = ? AND gtd_id = ?
                """
            ),
            (user_id, int(gtd_id)),
        ).fetchone()
        total = int(repo._row_to_dict(total_row).get("n") or 0)
        rows = conn.execute(
            repo._sql(
                """
                SELECT k.id AS kiz_id, k.kiz_short, k.gtin,
                       s.cis_status, s.cis_status_kind, s.cis_status_label,
                       s.cis_owner_inn, s.cis_status_error, s.cis_checked_at,
                       s.last_op, s.last_doc_id, s.last_doc_type,
                       s.last_op_status, s.last_op_error
                FROM supply_gtd_kiz k
                LEFT JOIN supply_gtd_chz_kiz_state s
                  ON s.user_id = k.user_id AND s.gtd_id = k.gtd_id
                 AND s.kiz_short = k.kiz_short
                WHERE k.user_id = ? AND k.gtd_id = ?
                ORDER BY k.id ASC
                """
            ),
            (user_id, int(gtd_id)),
        ).fetchall()

    items: list[dict[str, Any]] = []
    kind_counts: dict[str, int] = {}
    for r in rows:
        d = repo._row_to_dict(r)
        kind = str(d.get("cis_status_kind") or "").strip() or KIND_EMPTY
        label = str(d.get("cis_status_label") or "").strip() or (
            "Не проверен" if kind == KIND_EMPTY else ""
        )
        kind_counts[kind] = kind_counts.get(kind, 0) + 1
        if kind_filter and kind != kind_filter:
            continue
        items.append(
            {
                "kiz_id": int(d.get("kiz_id") or 0),
                "kiz_short": str(d.get("kiz_short") or ""),
                "gtin": str(d.get("gtin") or ""),
                "cis_status": str(d.get("cis_status") or ""),
                "cis_status_kind": kind,
                "cis_status_label": label,
                "cis_owner_inn": str(d.get("cis_owner_inn") or ""),
                "cis_status_error": str(d.get("cis_status_error") or ""),
                "cis_checked_at": str(d.get("cis_checked_at") or ""),
                "last_op": str(d.get("last_op") or ""),
                "last_doc_id": str(d.get("last_doc_id") or ""),
                "last_doc_type": str(d.get("last_doc_type") or ""),
                "last_op_status": str(d.get("last_op_status") or ""),
                "last_op_error": str(d.get("last_op_error") or ""),
            }
        )

    filtered_total = len(items)
    page = items[off : off + lim]
    return {
        "ok": True,
        "gtd": {
            "id": int(gtd.get("id") or gtd_id),
            "gtd_number": str(gtd.get("gtd_number") or ""),
            "kiz_count": int(gtd.get("kiz_count") or total),
            "note": str(gtd.get("note") or ""),
        },
        "total": total,
        "filtered_total": filtered_total,
        "offset": off,
        "limit": lim,
        "has_more": off + lim < filtered_total,
        "kind_counts": kind_counts,
        "items": page,
    }


def _start_run(
    repo: ReviewRepository,
    *,
    user_id: int,
    gtd_id: int,
    op: str,
    requested: int,
) -> int:
    with repo._connect() as conn:
        cur = conn.execute(
            repo._sql(
                """
                INSERT INTO supply_gtd_chz_runs (
                    user_id, gtd_id, op, status, requested, log_text, created_at
                ) VALUES (?, ?, ?, 'running', ?, '', NOW())
                RETURNING id
                """
            ),
            (user_id, int(gtd_id), op, int(requested)),
        )
        row = cur.fetchone()
    return int(repo._row_to_dict(row).get("id") or 0)


def _finish_run(
    repo: ReviewRepository,
    *,
    run_id: int,
    status: str,
    ok_count: int = 0,
    err_count: int = 0,
    log_text: str = "",
) -> None:
    with repo._connect() as conn:
        conn.execute(
            repo._sql(
                """
                UPDATE supply_gtd_chz_runs
                SET status = ?, ok_count = ?, err_count = ?, log_text = ?,
                    finished_at = NOW()
                WHERE id = ?
                """
            ),
            (
                str(status or "done")[:40],
                int(ok_count),
                int(err_count),
                str(log_text or "")[:50000],
                int(run_id),
            ),
        )


def get_run(
    repo: ReviewRepository, *, user_id: int, run_id: int
) -> dict[str, Any] | None:
    ensure_supply_gtd_chz_tables(repo)
    with repo._connect() as conn:
        row = conn.execute(
            repo._sql(
                """
                SELECT * FROM supply_gtd_chz_runs
                WHERE user_id = ? AND id = ?
                """
            ),
            (user_id, int(run_id)),
        ).fetchone()
    if not row:
        return None
    d = repo._row_to_dict(row)
    return {
        "id": int(d.get("id") or 0),
        "gtd_id": int(d.get("gtd_id") or 0),
        "op": str(d.get("op") or ""),
        "status": str(d.get("status") or ""),
        "requested": int(d.get("requested") or 0),
        "ok_count": int(d.get("ok_count") or 0),
        "err_count": int(d.get("err_count") or 0),
        "log_text": str(d.get("log_text") or ""),
        "created_at": str(d.get("created_at") or ""),
        "finished_at": str(d.get("finished_at") or ""),
    }


def latest_run_for_gtd(
    repo: ReviewRepository, *, user_id: int, gtd_id: int
) -> dict[str, Any] | None:
    ensure_supply_gtd_chz_tables(repo)
    with repo._connect() as conn:
        row = conn.execute(
            repo._sql(
                """
                SELECT id FROM supply_gtd_chz_runs
                WHERE user_id = ? AND gtd_id = ?
                ORDER BY id DESC
                LIMIT 1
                """
            ),
            (user_id, int(gtd_id)),
        ).fetchone()
    if not row:
        return None
    return get_run(
        repo, user_id=user_id, run_id=int(repo._row_to_dict(row).get("id") or 0)
    )


def _load_gtd_kiz_codes(
    repo: ReviewRepository,
    *,
    user_id: int,
    gtd_id: int,
    kiz_shorts: list[str] | None = None,
) -> list[str]:
    wanted = [str(x).strip() for x in (kiz_shorts or []) if str(x or "").strip()]
    with repo._connect() as conn:
        if wanted:
            found: list[str] = []
            for i in range(0, len(wanted), 500):
                chunk = wanted[i : i + 500]
                ph = ",".join("?" for _ in chunk)
                rows = conn.execute(
                    repo._sql(
                        f"""
                        SELECT kiz_short FROM supply_gtd_kiz
                        WHERE user_id = ? AND gtd_id = ?
                          AND kiz_short IN ({ph})
                        """
                    ),
                    (user_id, int(gtd_id), *chunk),
                ).fetchall()
                for r in rows:
                    ks = str(repo._row_to_dict(r).get("kiz_short") or "").strip()
                    if ks:
                        found.append(ks)
            pos = {k: i for i, k in enumerate(wanted)}
            found.sort(key=lambda k: pos.get(k, 10**9))
            return found
        rows = conn.execute(
            repo._sql(
                """
                SELECT kiz_short FROM supply_gtd_kiz
                WHERE user_id = ? AND gtd_id = ?
                ORDER BY id ASC
                """
            ),
            (user_id, int(gtd_id)),
        ).fetchall()
    return [
        str(repo._row_to_dict(r).get("kiz_short") or "").strip()
        for r in rows
        if str(repo._row_to_dict(r).get("kiz_short") or "").strip()
    ]


def _upsert_cis_state(
    repo: ReviewRepository,
    *,
    user_id: int,
    gtd_id: int,
    kiz_short: str,
    cis_status: str = "",
    cis_owner_inn: str = "",
    cis_status_error: str = "",
    participant_inn: str = "",
) -> None:
    label, kind = _display_kind(
        status=cis_status,
        owner_inn=cis_owner_inn,
        participant_inn=participant_inn,
        error=cis_status_error,
    )
    with repo._connect() as conn:
        conn.execute(
            repo._sql(
                """
                INSERT INTO supply_gtd_chz_kiz_state (
                    user_id, gtd_id, kiz_short, cis_status, cis_status_kind,
                    cis_status_label, cis_owner_inn, cis_status_error,
                    cis_checked_at, updated_at
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, NOW(), NOW())
                ON CONFLICT (user_id, gtd_id, kiz_short) DO UPDATE SET
                    cis_status = EXCLUDED.cis_status,
                    cis_status_kind = EXCLUDED.cis_status_kind,
                    cis_status_label = EXCLUDED.cis_status_label,
                    cis_owner_inn = EXCLUDED.cis_owner_inn,
                    cis_status_error = EXCLUDED.cis_status_error,
                    cis_checked_at = EXCLUDED.cis_checked_at,
                    updated_at = EXCLUDED.updated_at
                """
            ),
            (
                user_id,
                int(gtd_id),
                kiz_short,
                str(cis_status or "")[:80],
                str(kind or "")[:40],
                str(label or "")[:120],
                str(cis_owner_inn or "")[:20],
                str(cis_status_error or "")[:2000],
            ),
        )


