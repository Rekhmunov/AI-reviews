def refresh_gtd_cis_statuses(
    repo: ReviewRepository,
    *,
    user_id: int,
    gtd_id: int,
    token: str,
    kiz_shorts: list[str] | None = None,
) -> dict[str, Any]:
    ensure_supply_gtd_chz_tables(repo)
    _require_gtd(repo, user_id=user_id, gtd_id=gtd_id)
    settings = _chz_settings_ready(repo, user_id=user_id)
    codes = _load_gtd_kiz_codes(
        repo, user_id=user_id, gtd_id=gtd_id, kiz_shorts=kiz_shorts
    )
    if not codes:
        raise ValueError("Нет КИЗ для проверки")
    token_s = str(token or "").strip()
    if not token_s:
        raise ValueError("Нужен токен ЧЗ (подпишите УКЭП)")

    client = kiz_circ.chz_client_from_settings(settings)
    client.set_token(token_s)
    pg = str(settings.get("product_group") or "").strip()
    inn = str(settings.get("participant_inn") or "").strip()

    run_id = _start_run(
        repo, user_id=user_id, gtd_id=gtd_id, op="cis_status", requested=len(codes)
    )
    log: list[str] = []
    _append_log(log, f"Выгрузка статусов ЧЗ: кодов {len(codes)}")

    updated = found = missing = errors = 0
    try:
        for i in range(0, len(codes), CIS_CHUNK):
            part = codes[i : i + CIS_CHUNK]
            try:
                rows_api = client.cises_info(part, product_group=pg)
                parsed = [
                    kiz_circ.parse_cises_info_item(x if isinstance(x, dict) else None)
                    for x in rows_api
                ]
                nf = sum(
                    1
                    for p in parsed
                    if "не найден" in (p.get("error") or "").lower()
                    or p.get("error_code") == "404"
                )
                if pg and parsed and nf == len(parsed) == len(part):
                    _append_log(log, f"pg={pg}: все «не найден» — повтор без pg")
                    rows_api = client.cises_info(part, product_group="")
                    parsed = [
                        kiz_circ.parse_cises_info_item(
                            x if isinstance(x, dict) else None
                        )
                        for x in rows_api
                    ]
            except ChzTrueApiError as exc:
                errors += len(part)
                _append_log(log, f"Ошибка API: {exc}")
                for ks in part:
                    _upsert_cis_state(
                        repo,
                        user_id=user_id,
                        gtd_id=gtd_id,
                        kiz_short=ks,
                        cis_status_error=str(exc)[:500],
                        participant_inn=inn,
                    )
                    updated += 1
                continue

            by_key: dict[str, dict[str, str]] = {}
            for idx, p in enumerate(parsed):
                req = part[idx] if idx < len(part) else ""
                keys = {req, str(p.get("cis") or "").strip()}
                for k in list(keys):
                    if k:
                        keys.add(k.split("\x1d", 1)[0])
                for k in keys:
                    if k and k not in by_key:
                        by_key[k] = p

            for ks in part:
                hit = by_key.get(ks)
                if not hit:
                    for k, p in by_key.items():
                        if k.startswith(ks) or ks.startswith(k):
                            hit = p
                            break
                if not hit:
                    missing += 1
                    _upsert_cis_state(
                        repo,
                        user_id=user_id,
                        gtd_id=gtd_id,
                        kiz_short=ks,
                        cis_status_error="КИЗ не найден в ответе ЧЗ",
                        participant_inn=inn,
                    )
                    updated += 1
                    continue
                err = str(hit.get("error") or "").strip()
                status = str(hit.get("status") or "").strip()
                owner = str(hit.get("owner_inn") or "").strip()
                if err and not status:
                    errors += 1
                elif status:
                    found += 1
                else:
                    missing += 1
                _upsert_cis_state(
                    repo,
                    user_id=user_id,
                    gtd_id=gtd_id,
                    kiz_short=ks,
                    cis_status=status,
                    cis_owner_inn=owner,
                    cis_status_error=err,
                    participant_inn=inn,
                )
                updated += 1
            _append_log(log, f"Чанк {i // CIS_CHUNK + 1}: {len(part)} код.")

        _append_log(
            log,
            f"Готово: обновлено {updated}, найдено {found}, нет данных {missing}, ошибок {errors}",
        )
        _finish_run(
            repo,
            run_id=run_id,
            status="ok",
            ok_count=found,
            err_count=errors + missing,
            log_text="\n".join(log),
        )
    except Exception as exc:
        _append_log(log, f"Сбой: {exc}")
        _finish_run(
            repo,
            run_id=run_id,
            status="error",
            ok_count=found,
            err_count=errors + 1,
            log_text="\n".join(log),
        )
        raise

    return {
        "ok": True,
        "run_id": run_id,
        "requested": len(codes),
        "updated": updated,
        "found": found,
        "missing": missing,
        "errors": errors,
        "log_text": "\n".join(log),
    }


def _states_by_kiz(
    repo: ReviewRepository, *, user_id: int, gtd_id: int, kiz_shorts: list[str]
) -> dict[str, dict[str, Any]]:
    out: dict[str, dict[str, Any]] = {}
    if not kiz_shorts:
        return out
    with repo._connect() as conn:
        for i in range(0, len(kiz_shorts), 500):
            chunk = kiz_shorts[i : i + 500]
            ph = ",".join("?" for _ in chunk)
            rows = conn.execute(
                repo._sql(
                    f"""
                    SELECT * FROM supply_gtd_chz_kiz_state
                    WHERE user_id = ? AND gtd_id = ?
                      AND kiz_short IN ({ph})
                    """
                ),
                (user_id, int(gtd_id), *chunk),
            ).fetchall()
            for r in rows:
                d = repo._row_to_dict(r)
                out[str(d.get("kiz_short") or "")] = d
    return out


def prepare_gtd_chz_documents(
    repo: ReviewRepository,
    *,
    user_id: int,
    gtd_id: int,
    op: str,
    kiz_shorts: list[str],
) -> dict[str, Any]:
    ensure_supply_gtd_chz_tables(repo)
    gtd = _require_gtd(repo, user_id=user_id, gtd_id=gtd_id)
    settings = _chz_settings_ready(repo, user_id=user_id)
    op_s = str(op or "").strip().lower()
    if op_s not in {OP_WITHDRAW, OP_RETURN}:
        raise ValueError("op: withdraw или return")

    codes = _load_gtd_kiz_codes(
        repo, user_id=user_id, gtd_id=gtd_id, kiz_shorts=kiz_shorts
    )
    if not codes:
        raise ValueError("Выберите КИЗ")

    states = _states_by_kiz(repo, user_id=user_id, gtd_id=gtd_id, kiz_shorts=codes)
    eligible: list[str] = []
    skipped: list[dict[str, str]] = []
    for ks in codes:
        st = states.get(ks) or {}
        kind = str(st.get("cis_status_kind") or "").strip() or KIND_EMPTY
        last_op = str(st.get("last_op") or "").strip()
        last_op_status = str(st.get("last_op_status") or "").strip()
        # Already submitted to ЧЗ for this op — wait for status refresh / do not duplicate.
        if last_op_status == "submitted" and last_op == op_s:
            skipped.append(
                {
                    "kiz_short": ks,
                    "reason": "Уже отправлено в ЧЗ — сначала выгрузите статусы",
                }
            )
            continue
        if op_s == OP_WITHDRAW:
            if kind != KIND_IN:
                skipped.append(
                    {
                        "kiz_short": ks,
                        "reason": "Вывод доступен только для статуса «В обороте»",
                    }
                )
                continue
        else:
            if kind == KIND_TRANSFERRED:
                skipped.append(
                    {
                        "kiz_short": ks,
                        "reason": "Код передан другому ИНН — ввод недоступен",
                    }
                )
                continue
            if kind != KIND_OUT:
                skipped.append(
                    {
                        "kiz_short": ks,
                        "reason": "Ввод доступен для статуса «Выведен»",
                    }
                )
                continue
        eligible.append(ks)

    if not eligible:
        raise ValueError(
            "Нет подходящих КИЗ для операции. Сначала выгрузите статусы из ЧЗ."
        )

    inn = str(settings.get("participant_inn") or "").strip()
    pg = str(settings.get("product_group") or "").strip()
    kpp = str(settings.get("kpp") or "").strip()
    fias_id = str(settings.get("fias_id") or "").strip()
    if not kpp or not fias_id:
        place = kiz_circ.resolve_chz_place_details(
            repo, user_id=user_id, participant_inn=inn
        )
        if not kpp:
            kpp = str(place.get("kpp") or "").strip()
        if not fias_id:
            fias_id = str(place.get("fias_id") or "").strip()
    if len(re.sub(r"\D", "", inn)) == 12:
        kpp = ""

    if op_s == OP_WITHDRAW:
        if not fias_id or (len(re.sub(r"\D", "", inn)) == 10 and not kpp):
            raise ValueError(
                "Для вывода DISTANCE укажите КПП (ООО) и ФИАС МОД в Настройки → ЧЗ"
            )

    gtd_number = str(gtd.get("gtd_number") or "").strip()
    doc_date = _moscow_today()
    documents: list[dict[str, Any]] = []

    for part_idx, start in enumerate(range(0, len(eligible), DOC_PRODUCTS_LIMIT), start=1):
        part = eligible[start : start + DOC_PRODUCTS_LIMIT]
        if op_s == OP_WITHDRAW:
            products = [{"cis": ks, "product_cost": 0} for ks in part]
            doc_number = f"GTD-{int(gtd_id)}-{doc_date.replace('-', '')}-{part_idx}"
            body = build_lk_receipt_document(
                inn=inn,
                action="DISTANCE",
                document_number=doc_number,
                document_date=doc_date,
                primary_document_type="OTHER",
                primary_document_custom_name=f"ГТД {gtd_number}"[:255],
                products=products,
                kpp=kpp,
                fias_id=fias_id,
            )
            documents.append(
                {
                    "doc_type": "LK_RECEIPT",
                    "product_group": pg,
                    "title": f"Вывод · ГТД {gtd_number} · часть {part_idx}",
                    "kiz_shorts": part,
                    "product_document": body,
                    "sign_payload_b64": _b64_json(body),
                }
            )
        else:
            products = [{"ki": ks} for ks in part]
            ret_type = str(settings.get("return_type") or "REMOTE_SALE_RETURN").strip()
            body = build_lp_return_document(
                inn=inn,
                return_type=ret_type or "REMOTE_SALE_RETURN",
                products=products,
                paid=False,
            )
            documents.append(
                {
                    "doc_type": "LP_RETURN",
                    "product_group": pg,
                    "title": f"Ввод · ГТД {gtd_number} · часть {part_idx}",
                    "kiz_shorts": part,
                    "product_document": body,
                    "sign_payload_b64": _b64_json(body),
                }
            )

    return {
        "ok": True,
        "op": op_s,
        "gtd_id": int(gtd_id),
        "gtd_number": gtd_number,
        "documents": documents,
        "eligible": len(eligible),
        "skipped": skipped,
        "warnings": [],
        "settings": {
            "cert_thumbprint": str(settings.get("cert_thumbprint") or ""),
            "participant_inn": inn,
            "product_group": pg,
        },
    }


def submit_gtd_chz_documents(
    repo: ReviewRepository,
    *,
    user_id: int,
    gtd_id: int,
    token: str,
    op: str,
    documents: list[dict[str, Any]],
) -> dict[str, Any]:
    ensure_supply_gtd_chz_tables(repo)
    _require_gtd(repo, user_id=user_id, gtd_id=gtd_id)
    settings = _chz_settings_ready(repo, user_id=user_id)
    op_s = str(op or "").strip().lower()
    if op_s not in {OP_WITHDRAW, OP_RETURN}:
        raise ValueError("op: withdraw или return")
    token_s = str(token or "").strip()
    if not token_s:
        raise ValueError("Нужен токен ЧЗ (подпишите УКЭП)")
    docs = [d for d in (documents or []) if isinstance(d, dict)]
    if not docs:
        raise ValueError("Нет документов для отправки")

    client: ChzTrueApiClient = kiz_circ.chz_client_from_settings(settings)
    client.set_token(token_s)
    pg_default = str(settings.get("product_group") or "").strip()

    requested = sum(len(d.get("kiz_shorts") or []) for d in docs)
    run_id = _start_run(
        repo, user_id=user_id, gtd_id=gtd_id, op=op_s, requested=requested
    )
    log: list[str] = []
    label = "вывод" if op_s == OP_WITHDRAW else "ввод"
    _append_log(log, f"Отправка в ЧЗ ({label}): док. {len(docs)}")

    submitted = failed = 0
    results: list[dict[str, Any]] = []
    try:
        for i, doc in enumerate(docs, start=1):
            doc_type = str(doc.get("doc_type") or "").strip()
            pg = str(doc.get("product_group") or pg_default).strip()
            sig = str(
                doc.get("signature_base64") or doc.get("signature_b64") or ""
            ).strip()
            payload_b64 = str(
                doc.get("product_document_b64") or doc.get("sign_payload_b64") or ""
            ).strip()
            kiz_list = [
                str(x).strip()
                for x in (doc.get("kiz_shorts") or [])
                if str(x or "").strip()
            ]
            title = str(doc.get("title") or doc_type)
            if not doc_type or not sig or not payload_b64:
                failed += 1
                _append_log(log, f"{i}. {title}: нет подписи/payload")
                _mark_op_state(
                    repo,
                    user_id=user_id,
                    gtd_id=gtd_id,
                    kiz_shorts=kiz_list,
                    op=op_s,
                    doc_type=doc_type,
                    op_status="error",
                    op_error="Нет подписи или payload",
                )
                results.append({"title": title, "ok": False, "error": "no signature"})
                continue
            try:
                doc_id = client.create_document(
                    doc_type=doc_type,
                    product_group=pg,
                    signature_b64=sig,
                    product_document_b64=payload_b64,
                )
                submitted += 1
                _append_log(
                    log, f"{i}. {title}: OK id={doc_id} ({len(kiz_list)} КИЗ)"
                )
                _mark_op_state(
                    repo,
                    user_id=user_id,
                    gtd_id=gtd_id,
                    kiz_shorts=kiz_list,
                    op=op_s,
                    doc_id=str(doc_id),
                    doc_type=doc_type,
                    op_status="submitted",
                )
                results.append(
                    {
                        "title": title,
                        "ok": True,
                        "document_id": str(doc_id),
                        "kiz_count": len(kiz_list),
                    }
                )
            except ChzTrueApiError as exc:
                failed += 1
                _append_log(log, f"{i}. {title}: ошибка {exc}")
                _mark_op_state(
                    repo,
                    user_id=user_id,
                    gtd_id=gtd_id,
                    kiz_shorts=kiz_list,
                    op=op_s,
                    doc_type=doc_type,
                    op_status="error",
                    op_error=str(exc)[:2000],
                )
                results.append({"title": title, "ok": False, "error": str(exc)})

        status = (
            "ok"
            if submitted and not failed
            else ("error" if not submitted else "partial")
        )
        _append_log(log, f"Итого: отправлено {submitted}, ошибок {failed}")
        _finish_run(
            repo,
            run_id=run_id,
            status=status,
            ok_count=submitted,
            err_count=failed,
            log_text="\n".join(log),
        )
    except Exception as exc:
        _append_log(log, f"Сбой: {exc}")
        _finish_run(
            repo,
            run_id=run_id,
            status="error",
            ok_count=submitted,
            err_count=failed + 1,
            log_text="\n".join(log),
        )
        raise

    return {
        "ok": failed == 0 and submitted > 0,
        "run_id": run_id,
        "submitted": submitted,
        "failed": failed,
        "results": results,
        "log_text": "\n".join(log),
    }
